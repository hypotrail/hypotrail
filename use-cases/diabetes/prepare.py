"""Materialize the diabetes progression case from the installed scikit-learn.

The data are not committed to this repository: neither the scikit-learn package files
nor its licence state the terms under which the data may be redistributed (see
README.md). This script copies them from the installed package, without any download:

* ``data/diabetes.csv``: the 442 rows of the **raw** feature file
  ``sklearn/datasets/data/diabetes_data_raw.csv.gz`` (what ``load_diabetes(scaled=False)``
  returns, so age is in years and sex is coded 1 and 2), followed by the target of
  ``diabetes_target.csv.gz`` written as an integer, with a header;
* ``case.yaml``: the ``hypotrail.case/1`` adapter, with the sha256 of that CSV.

``case.yaml`` is committed and generated by this script; edit the script, never the
YAML. The CSV is git-ignored. Usage (from the repository root)::

    uv run --project framework python use-cases/diabetes/prepare.py            # here
    uv run --project framework python use-cases/diabetes/prepare.py --out DIR  # a copy
    uv run --project framework python use-cases/diabetes/prepare.py --check

No model is trained.
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import sys
from importlib import resources
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DATA = 'data/diabetes.csv'
DESCR = 'sklearn/datasets/descr/diabetes.rst'
RAW_FILE = 'sklearn/datasets/data/diabetes_data_raw.csv.gz'
TARGET_FILE = 'sklearn/datasets/data/diabetes_target.csv.gz'
TARGET = 'progression'
# name, type, description, descr line, unit
FEATURES = [
    ('age', 'numeric', 'Age', 20, 'years'),
    ('sex', 'category', 'Sex, coded 1 and 2 in the raw file; which code is which is not '
                        'documented', 21, None),
    ('bmi', 'numeric', 'Body mass index', 22, None),
    ('bp', 'numeric', 'Average blood pressure', 23, None),
    ('s1', 'numeric', 'tc, total serum cholesterol', 24, None),
    ('s2', 'numeric', 'ldl, low-density lipoproteins', 25, None),
    ('s3', 'numeric', 'hdl, high-density lipoproteins', 26, None),
    ('s4', 'numeric', 'tch, total cholesterol / HDL', 27, None),
    ('s5', 'numeric', 'ltg, possibly log of serum triglycerides level (the documentation '
                      'itself is unsure)', 28, None),
    ('s6', 'numeric', 'glu, blood sugar level', 29, None),
]
HEADER = ('# Generated by use-cases/diabetes/prepare.py from the installed scikit-learn.\n'
          '# Do not edit by hand: change prepare.py and regenerate with\n'
          '#   uv run --project framework python use-cases/diabetes/prepare.py\n'
          '# A case states facts and assumptions; human decisions live in study state.\n')


def _package(name: str) -> bytes:
    return resources.files('sklearn.datasets.data').joinpath(name).read_bytes()


def dataset_bytes() -> tuple[bytes, bytes, bytes]:
    """``(csv bytes, raw feature file bytes, target file bytes)``."""
    raw_gz, target_gz = _package('diabetes_data_raw.csv.gz'), _package('diabetes_target.csv.gz')
    rows = gzip.decompress(raw_gz).decode('ascii').splitlines()
    targets = gzip.decompress(target_gz).decode('ascii').split()
    if len(rows) != 442 or len(targets) != 442:
        raise SystemExit(f'Expected 442 rows, found {len(rows)} and {len(targets)}')
    out = [','.join([f[0] for f in FEATURES] + [TARGET])]
    for line, target in zip(rows, targets):
        fields = line.split()
        value = float(target)
        if len(fields) != len(FEATURES) or value != int(value):
            raise SystemExit(f'Unexpected row {line!r} / target {target!r}')
        out.append(','.join(fields + [str(int(value))]))
    return ('\n'.join(out) + '\n').encode('ascii'), raw_gz, target_gz


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def case_document(data: bytes, raw_gz: bytes, target_gz: bytes) -> dict:
    rows = data.count(b'\n') - 1
    scenario = (f'Scenario: measured at the baseline visit, when the estimate is made. '
                f'{DESCR}:6-9 calls these ten variables baseline variables.')
    variables = []
    for name, kind, text, line, unit in FEATURES:
        entry = {'name': name, 'type': kind, 'role': 'feature'}
        if unit:
            entry['unit'] = unit
        entry.update({'description': f'{text}, at baseline.', 'status': 'documented_fact',
                      'source': f'{DESCR}:{line}',
                      'availability': {'value': 'available_at_prediction',
                                       'status': 'scenario_assumption', 'source': scenario},
                      'special_values': []})
        variables.append(entry)
    variables.append({
        'name': TARGET, 'type': 'integer', 'role': 'target', 'unit': 'points',
        'description': 'A quantitative measure of disease progression one year after '
                       'baseline. The documentation gives neither its unit nor its scale: '
                       '"points" names the score itself.',
        'status': 'documented_fact', 'source': f'{DESCR}:8-9,17',
        'availability': {'value': 'not_available', 'status': 'scenario_assumption',
                         'source': 'The outcome to estimate; it is measured one year after the '
                                   'baseline visit.'},
        'special_values': []})
    return {
        'schema': 'hypotrail.case/1',
        'id': 'sklearn-diabetes',
        'title': 'Diabetes progression · scikit-learn copy',
        'description': 'Estimate the disease progression of a diabetes patient one year after '
                       'a baseline visit, from ten measurements taken at that visit.',
        'provenance': {
            'kind': 'public_dataset',
            'name': 'Diabetes dataset (Efron, Hastie, Johnstone and Tibshirani, 2004)',
            'documented_in': f'{DESCR}:1-38',
            'source_url': 'https://www4.stat.ncsu.edu/~boos/var.select/diabetes.html',
            'copied_from': f'{RAW_FILE} and {TARGET_FILE} of the installed scikit-learn '
                           f'(load_diabetes(scaled=False)); no download',
            'package_files_sha256': {RAW_FILE: _sha(raw_gz), TARGET_FILE: _sha(target_gz)},
            'license': 'Not stated in the scikit-learn package files. The scikit-learn '
                       'licence (BSD-3-Clause, COPYING) covers its software. The data are '
                       'therefore not committed here; prepare.py copies them locally.',
            'references': ['Bradley Efron, Trevor Hastie, Iain Johnstone and Robert Tibshirani '
                           '(2004) "Least Angle Regression," Annals of Statistics (with '
                           'discussion), 407-499.'],
        },
        'dataset': {'path': DATA, 'format': 'csv', 'sep': ',', 'encoding': 'utf-8',
                    'decimal': '.', 'header': True, 'sha256': _sha(data), 'rows': rows,
                    'columns': len(variables)},
        'target': {'column': TARGET, 'positive_label': None},
        'row_key': {'rule': 'source_line', 'format': 'L<line>',
                    'description': 'Physical 1-based line number in diabetes.csv; the header is '
                                   'line 1, so the first data row is L2. The key is anchored to '
                                   'the dataset sha256.'},
        'facts': [
            {'id': 'instances', 'value': '442 diabetes patients, ten baseline variables and the '
                                         'response', 'status': 'documented_fact',
             'source': f'{DESCR}:6-9,13'},
            {'id': 'raw_values',
             'value': f'{DATA} holds the raw feature values. The standardisation described in '
                      f'{DESCR}:31 applies to the default load_diabetes() output, not to this '
                      f'file.',
             'status': 'observed', 'source': 'use-cases/diabetes/prepare.py'},
            {'id': 'sex_coding', 'value': 'Sex is coded 1 and 2; the meaning of each code is '
                                          'not documented.',
             'status': 'unknown', 'source': f'{DESCR}:21'},
            {'id': 'units', 'value': 'Only age has a documented unit (years). The units of '
                                     'the other measurements and of the target are not '
                                     'documented.',
             'status': 'documented_fact', 'source': f'{DESCR}:17-29'},
            {'id': 'intended_use',
             'value': 'Exercise: estimate which patients will progress most within a year, to '
                      'plan follow-up visits.',
             'status': 'scenario_assumption', 'source': 'Teaching scenario (README.md)'},
            {'id': 'prediction_time', 'value': 'At the baseline visit, once its measurements '
                                               'are available.',
             'status': 'scenario_assumption', 'source': 'Teaching scenario (README.md)'},
        ],
        'variables': variables,
        'special_values': [],
        'structure': {
            'row_unit': {'value': 'One diabetes patient', 'status': 'documented_fact',
                         'source': f'{DESCR}:6-8'},
            'group_column': {'value': None, 'status': 'unknown',
                             'source': 'No identifier; one row per patient according to '
                                       'the documentation'},
            'time_column': {'value': None, 'status': 'unknown',
                            'source': 'No visit date in the copy'},
            'duplicates': {'value': 0, 'status': 'observed',
                           'source': f'Structural inspection of {DATA}'},
        },
        'task': 'regression',
        'prior_exposure': [
            {'value': 'Every row is bundled with scikit-learn and used in countless tutorials, '
                      'including the Least Angle Regression paper; a language model has likely '
                      'seen analyses of it. No row is unseen.',
             'status': 'scenario_assumption', 'source': 'Distribution of the dataset'},
        ],
    }


def render(document: dict) -> str:
    return HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def materialize(out: Path) -> Path:
    """Write ``data/diabetes.csv`` and ``case.yaml`` under ``out``; return the case path."""
    data, raw_gz, target_gz = dataset_bytes()
    out = Path(out)
    (out / 'data').mkdir(parents=True, exist_ok=True)
    (out / DATA).write_bytes(data)
    case = out / 'case.yaml'
    text = render(case_document(data, raw_gz, target_gz))
    if not case.is_file() or case.read_text(encoding='utf-8') != text:
        case.write_text(text, encoding='utf-8')
    return case


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--out', type=Path, default=HERE)
    parser.add_argument('--check', action='store_true',
                        help='exit 1 if the committed case.yaml differs from a fresh generation')
    args = parser.parse_args(argv)
    if args.check:
        fresh = render(case_document(*dataset_bytes()))
        if (HERE / 'case.yaml').read_text(encoding='utf-8') != fresh:
            print('case.yaml differs from a fresh generation', file=sys.stderr)
            return 1
        print('case.yaml is up to date')
        return 0
    print(materialize(args.out))
    return 0


if __name__ == '__main__':
    sys.exit(main())
