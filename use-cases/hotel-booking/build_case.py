"""Generate the Hotel booking demand case (``case.yaml``) and verify its data.

The source is the "Hotel booking demand datasets" of Antonio, de Almeida and Nunes (2019,
Data in Brief 22:41-49, doi 10.1016/j.dib.2018.11.126): two hotels, H1 a resort hotel in
the Algarve and H2 a city hotel in Lisbon, one row per booking due to arrive between
1 July 2015 and 31 August 2017. The authors' files were not reachable from the preparation
environment; the combined file of the tidytuesday mirror (``hotels.csv``, 2020-02-11, both
hotels, a ``hotel`` column added and the column names converted to snake case) was
downloaded and checked against the counts the article publishes (see ``README.md``).

The case keeps the **Resort Hotel (H1)** rows only. ``data/hotel-resort.csv`` is derived
from the mirror file by ``--derive``: the Resort rows, without the constant ``hotel``
column, sorted by arrival date (year, month, day of month; a stable sort keeps the mirror's
order within a date). Every cell is copied as text, unchanged. The declared row order
(``order: {by: line}``) is therefore the arrival order, and the sealed final test is the
latest fifth of the arrivals.

* ``--derive PATH``: rebuild ``data/hotel-resort.csv`` from the mirror's ``hotels.csv``
  (its sha256 and the article's counts are checked first) and regenerate ``case.yaml``;
* ``--check``: exits 1 when the committed ``case.yaml`` differs from a fresh generation;
* ``--verify``: re-runs the integrity checks of ``data/hotel-resort.csv`` and prints them;
* ``--out DIR``: writes a complete case folder (``case.yaml`` and ``data/``) in DIR, for tests.

``case.yaml`` is generated: edit this script, never the YAML. No model is trained. The
mirror file is untrusted input: it is read with pandas as text only (``dtype=str``,
``keep_default_na=False``) and never executed.

    uv run --project framework python use-cases/hotel-booking/build_case.py
    uv run --project framework python use-cases/hotel-booking/build_case.py --check
    uv run --project framework python use-cases/hotel-booking/build_case.py --verify
"""
