def render(document: dict) -> str:
    return HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--derive', type=Path, metavar='HOTELS_CSV')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args(argv)
    if args.derive:
        mirror = args.derive.read_bytes()
        problems = mirror_problems(mirror)
        for p in problems:
            print('MISMATCH', p)
        if problems:
            return 1
        (HERE / 'data').mkdir(exist_ok=True)
        (HERE / DATA).write_bytes(derive(mirror))
        print(f'wrote {HERE / DATA}')
    data = (HERE / DATA).read_bytes()
    if args.verify:
        problems = verify(data)
        s = inspect(data)
        print(f'sha256 {hashlib.sha256(data).hexdigest()}')
        print(f'rows {s["rows"]}, columns {len(s["header"])}, {TARGET} {dict(s["labels"])}, '
              f'arrivals {_date(s["first"])} to {_date(s["last"])} (ordered: {s["ordered"]}), '
              f'final-test cut at {_date(s["cut_date"])}, identical rows '
              f'{s["duplicate_rows"]} in {s["duplicate_groups"]} groups, country NULL '
              f'{s["country_null"]}')
        for p in problems:
            print('MISMATCH', p)
        return 1 if problems else 0
    text = render(case_document(data))
    if args.check:
        same = (HERE / 'case.yaml').read_text(encoding='utf-8') == text
        print('case.yaml is up to date' if same else 'case.yaml differs from a fresh generation')
        return 0 if same else 1
    target = args.out or HERE
    if args.out:
        (target / 'data').mkdir(parents=True, exist_ok=True)
        shutil.copyfile(HERE / DATA, target / DATA)
    (target / 'case.yaml').write_text(text, encoding='utf-8')
    print(f'wrote {target / "case.yaml"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
