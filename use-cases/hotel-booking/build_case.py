def _date(t) -> str:
    return f'{t[0]:04d}-{t[1]:02d}-{t[2]:02d}'


def _order(v: dict) -> dict:
    keys = ('name', 'type', 'role', 'unit', 'group', 'description', 'labels', 'status', 'source',
            'range', 'availability', 'special_values')
    return {k: v[k] for k in keys if k in v}


