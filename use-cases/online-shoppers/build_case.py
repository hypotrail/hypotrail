def l10n_document(data: bytes, case_text: str) -> dict:
    """The translation sidecar of the ``case.yaml`` whose text is ``case_text``."""
    document = case_document(data)
    facts = facts_fr(data)
    assert [f['id'] for f in document['facts']] == list(facts), list(facts)
    variables_ = {}
    for v in document['variables']:
        source = v['availability']['source']
        french = TARGET_AVAILABILITY_FR if v['name'] == TARGET else AVAILABILITY_FR[source]
        variables_[v['name']] = {'group': {'fr': GROUPS_FR[v['group']]},
                                 'availability': {'source': {'fr': french}}}
    specials = [{'column': s['column'], 'value': s['value'],
                 'meaning': {'fr': SPECIAL_FR[(s['column'], s['value'])]}}
                for s in document['special_values']]
    return {'schema': 'hypotrail.case_l10n/1',
            'case': {'id': document['id'],
                     'sha256': hashlib.sha256(case_text.encode('utf-8')).hexdigest()},
            'facts': {k: {'fr': v} for k, v in facts.items()},
            'structure': {'row_unit': {'fr': 'Une session de navigation'}},
            'special_values': specials,
            'variables': variables_}


def render_l10n(document: dict) -> str:
    return L10N_HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True,
                                        width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args(argv)
    data = (HERE / DATA).read_bytes()
    if args.verify:
        problems = verify(data)
        s = inspect(data)
        print(f'sha256 {hashlib.sha256(data).hexdigest()}')
        print(f'rows {s["rows"]}, columns {len(s["header"])}, Revenue {dict(s["labels"])}, '
              f'identical rows {s["duplicate_rows"]} in {s["duplicate_groups"]} groups')
        for p in problems:
            print('MISMATCH', p)
        return 1 if problems else 0
    text = render(case_document(data))
    l10n = render_l10n(l10n_document(data, text))
    if args.check:
        same = (HERE / 'case.yaml').read_text(encoding='utf-8') == text
        print('case.yaml is up to date' if same else 'case.yaml differs from a fresh generation')
        sidecar = HERE / L10N_FILE
        same_l10n = sidecar.is_file() and sidecar.read_text(encoding='utf-8') == l10n
        print(f'{L10N_FILE} is up to date' if same_l10n
              else f'{L10N_FILE} differs from a fresh generation')
        return 0 if same and same_l10n else 1
    target = args.out or HERE
    if args.out:
        (target / 'data').mkdir(parents=True, exist_ok=True)
        shutil.copyfile(HERE / DATA, target / DATA)
    (target / 'case.yaml').write_text(text, encoding='utf-8')
    (target / L10N_FILE).write_text(l10n, encoding='utf-8')
    print(f'wrote {target / "case.yaml"} and {target / L10N_FILE}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
