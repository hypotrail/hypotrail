def _order(v: dict) -> dict:
    keys = ('name', 'type', 'role', 'unit', 'group', 'description', 'labels', 'status', 'source',
            'range', 'availability', 'special_values')
    return {k: v[k] for k in keys if k in v}


def inspect(data: bytes) -> dict:
    """Structural counts of the CSV (rows, columns, labels, identical rows, months)."""
    rows = list(csv.reader(io.StringIO(data.decode('utf-8'), newline='')))
    header, body = rows[0], rows[1:]
    groups = Counter(tuple(r) for r in body)
    return {'header': header, 'rows': len(body), 'widths': sorted({len(r) for r in body}),
            'labels': Counter(r[-1] for r in body),
            'duplicate_rows': sum(c - 1 for c in groups.values() if c > 1),
            'duplicate_groups': sum(1 for c in groups.values() if c > 1),
            'rows_in_groups': sum(c for c in groups.values() if c > 1),
            'months': sorted({r[header.index('Month')] for r in body}),
            'crlf': data.count(b'\r\n') == data.count(b'\n')}


def verify(data: bytes) -> list[str]:
    """Mismatches between the CSV and the figures UCI publishes (empty when it matches)."""
    s = inspect(data)
    problems = []
    if s['rows'] != UCI_ROWS:
        problems.append(f'{s["rows"]} rows, UCI publishes {UCI_ROWS}')
    if len(s['header']) != UCI_COLUMNS or s['widths'] != [UCI_COLUMNS]:
        problems.append(f'columns {len(s["header"])}/{s["widths"]}, UCI publishes {UCI_COLUMNS}')
    if s['labels'] != Counter({'TRUE': UCI_POSITIVE, 'FALSE': UCI_NEGATIVE}):
        problems.append(f'Revenue {dict(s["labels"])}, UCI publishes TRUE {UCI_POSITIVE}, '
                        f'FALSE {UCI_NEGATIVE}')
    return problems


