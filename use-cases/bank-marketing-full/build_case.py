"""Generate the Bank Marketing (full file) case (``case.yaml``) and verify its data.

``bank-full.csv`` holds every row of the UCI Bank Marketing campaigns, ordered by date
from May 2008 to November 2010 (``data/bank-names.txt:31``); the ``bank-marketing`` case
uses ``bank.csv``, a random 10 % sample of it (line 32), and stays unchanged for
compatibility. The data are committed (CC BY 4.0, owner decision 2026-10-19). They were
obtained from two public GitHub mirrors with identical bytes, because the UCI repository was
not reachable from the preparation environment, and verified against the figures UCI
publishes and against ``bank.csv`` (see ``README.md`` and the ``data_*`` facts below).

The variable dictionary, the scenario facts and the special values are those of
``../bank-marketing/case.yaml`` (same columns, same documentation file, copied unchanged as
``data/bank-names.txt``), so the two cases say the same things about the same columns.
What differs: the dataset, the declared row order (``order: {by: line}``: the sealed final
test is the last 20 % of the rows in time, less the rows of ``bank.csv``), the verification
facts, the prior exposure (with ``prior_exposed_rows``, the keys of the ``bank.csv`` records
in ``data/prior-exposed-rows.txt``, generated here), and the scenario default capacity
(``scenario_defaults.capacity_share``, 10 %).

* ``--check``: exits 1 when the committed ``case.yaml`` differs from a fresh generation
  (also after a change of ``../bank-marketing/case.yaml``);
* ``--verify``: re-runs the integrity checks of ``bank-full.csv`` and prints them;
* ``--out DIR``: writes a complete case folder in DIR, for tests.

``case.yaml`` is generated: edit this script, never the YAML. No model is trained.

    uv run --project framework python use-cases/bank-marketing-full/build_case.py
    uv run --project framework python use-cases/bank-marketing-full/build_case.py --check
    uv run --project framework python use-cases/bank-marketing-full/build_case.py --verify
"""
from __future__ import annotations

import argparse
import copy
import csv
import hashlib
import io
import shutil
import sys
from collections import Counter
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
SAMPLE_CASE = HERE.parent / 'bank-marketing'
DATA = 'data/bank-full.csv'
NAMES = 'data/bank-names.txt'
# WP-B6a (review M2): the row keys of the bank-full.csv records that are bank.csv records,
# one per line; the engine keeps them out of the sealed final test (prior_exposed_rows).
PRIOR_ROWS = 'data/prior-exposed-rows.txt'
MIRRORS = ('https://raw.githubusercontent.com/PacktWorkshops/The-Data-Science-Workshop/master/'
           'Chapter03/bank-full.csv',
           'https://raw.githubusercontent.com/fenago/datasets/main/bank-full.csv')
GIT_BLOB = 'd7a2ede53415cea37bbd3acd8c1962e619f83d5f'
UCI_ROWS, UCI_COLUMNS, UCI_YES = 45211, 17, 5289
HEADER = ('# Generated by use-cases/bank-marketing-full/build_case.py.\n'
          '# Do not edit by hand: change build_case.py (or ../bank-marketing/case-supplement.yaml)\n'
          '# and regenerate with\n'
          '#   uv run --project framework python use-cases/bank-marketing-full/build_case.py\n'
          '# A case states facts and assumptions; human decisions live in study state.\n')


def _rows(data: bytes) -> tuple[list[str], list[list[str]]]:
    rows = list(csv.reader(io.StringIO(data.decode('utf-8'), newline=''), delimiter=';'))
    return rows[0], rows[1:]


def inspect(data: bytes) -> dict:
    header, body = _rows(data)
    sample_header, sample = _rows((SAMPLE_CASE / 'data' / 'bank.csv').read_bytes())
    full = Counter(tuple(r) for r in body)
    missing = Counter(tuple(r) for r in sample) - full
    months, runs = header.index('month'), []
    for r in body:
        if not runs or runs[-1] != r[months]:
            runs.append(r[months])
    return {'header': header, 'rows': len(body), 'widths': sorted({len(r) for r in body}),
            'labels': Counter(r[-1] for r in body),
            'duplicate_rows': sum(c - 1 for c in full.values() if c > 1),
            'sample_rows': len(sample), 'sample_header_equal': sample_header == header,
            'sample_not_contained': sum(missing.values()), 'month_runs': runs}


def prior_rows_text(data: bytes) -> str:
    """The row keys (``L<line>``, the header is line 1) of the records of ``bank-full.csv``
    that are records of ``bank.csv`` (exact record match after csv parsing), in line order.
    bank-full.csv has no exact duplicate, so each bank.csv record names one line."""
    _, body = _rows(data)
    _, sample = _rows((SAMPLE_CASE / 'data' / 'bank.csv').read_bytes())
    wanted = set(tuple(r) for r in sample)
    keys = [f'L{i + 2}' for i, r in enumerate(body) if tuple(r) in wanted]
    return ''.join(f'{k}\n' for k in keys)


def verify(data: bytes) -> list[str]:
    s = inspect(data)
    problems = []
    if s['rows'] != UCI_ROWS:
        problems.append(f'{s["rows"]} rows, UCI publishes {UCI_ROWS}')
    if len(s['header']) != UCI_COLUMNS or s['widths'] != [UCI_COLUMNS]:
        problems.append(f'columns {len(s["header"])}/{s["widths"]}, UCI publishes {UCI_COLUMNS}')
    if s['labels']['yes'] != UCI_YES or set(s['labels']) != {'yes', 'no'}:
        problems.append(f'y {dict(s["labels"])}, UCI publishes yes {UCI_YES}')
    if not s['sample_header_equal'] or s['sample_not_contained']:
        problems.append(f'{s["sample_not_contained"]} rows of bank.csv are not rows of '
                        f'bank-full.csv (header equal: {s["sample_header_equal"]})')
    return problems


def _sample_document() -> dict:
    """``../bank-marketing/case.yaml``, read without verifying its dataset."""
    return yaml.safe_load((SAMPLE_CASE / 'case.yaml').read_text(encoding='utf-8'))


def case_document(data: bytes) -> dict:
    s = inspect(data)
    sha = hashlib.sha256(data).hexdigest()
    prior = prior_rows_text(data).encode('utf-8')
    n_prior = prior.count(b'\n')
    base = _sample_document()
    assert [v['name'] for v in base['variables']] == s['header']
    names = (HERE / NAMES).read_bytes()
    assert names == (SAMPLE_CASE / NAMES).read_bytes(), 'data/bank-names.txt differs from Bank'
    inspection = f'Structural inspection of {DATA}'
    facts = []
    for fact in copy.deepcopy(base['facts']):
        if fact['id'] == 'repeated_observations':
            fact['source'] = f'{inspection} (no client identifier, no year)'
        facts.append(fact)
    first, last = s['month_runs'][0], s['month_runs'][-1]
    facts += [
        {'id': 'data_rows_columns',
         'value': f'{s["rows"]} data rows and {len(s["header"])} columns, as UCI publishes '
                  f'({UCI_ROWS} instances, 16 attributes and the output)',
         'status': 'observed',
         'source': f'{inspection} and {NAMES}:37,39; verification method: build_case.py '
                   f'--verify (csv parsing with ";", every row has {UCI_COLUMNS} fields)'},
        {'id': 'data_class_counts',
         'value': f'y is "yes" in {s["labels"]["yes"]} rows and "no" in {s["labels"]["no"]}, '
                  f'as UCI publishes ({UCI_YES} yes). A structural count over every row, not '
                  f'a rate studied on training rows.',
         'status': 'observed',
         'source': f'{inspection}; verification method: build_case.py --verify'},
        {'id': 'data_contains_sample',
         'value': f'Every one of the {s["sample_rows"]} rows of bank.csv (the bank-marketing '
                  f'case) is a row of this file, counted with multiplicity, with the same '
                  f'header and quoting: bank.csv is the 10 % sample this file documents.',
         'status': 'observed',
         'source': f'{inspection} and ../bank-marketing/data/bank.csv; verification method: '
                   f'build_case.py --verify (multiset comparison of parsed rows); '
                   f'{NAMES}:32'},
        {'id': 'data_mirror',
         'value': f'Obtained on 2026-10-19 from two public mirrors with identical bytes '
                  f'({MIRRORS[0]} and {MIRRORS[1]}; git blob {GIT_BLOB}); sha256 {sha}. '
                  f'UCI was unreachable from the preparation environment.',
         'status': 'observed',
         'source': 'Download log of the preparation (README.md, "Provenance and verification")'},
        {'id': 'row_order',
         'value': f'Rows are ordered by date from May 2008 to November 2010. The month column '
                  f'follows that order: it runs from {first} to {last} in '
                  f'{len(s["month_runs"])} consecutive runs, with no year.',
         'status': 'documented_fact',
         'source': f'{NAMES}:31 (order); {inspection} (month runs)'},
    ]
    provenance = dict(base['provenance'])
    provenance.update(
        file='bank-full.csv',
        obtained_from=list(MIRRORS),
        obtained_on='2026-10-19',
        obtained_because='archive.ics.uci.edu was blocked by the preparation environment\'s '
                         'network proxy',
        file_sha256=sha,
        verification='build_case.py --verify: rows, columns and y counts equal the figures '
                     'UCI publishes, and every row of bank.csv is a row of this file; the '
                     'file was not compared byte for byte with the UCI archive.')
    structure = copy.deepcopy(base['structure'])
    structure['time_column'] = {
        'value': None, 'status': 'documented_fact',
        'source': f'No date column: day and month of the last contact without the year. The '
                  f'rows are ordered by date ({NAMES}:31); the case declares that order by '
                  f'line (order).'}
    structure['duplicates'] = {'value': s['duplicate_rows'], 'status': 'observed',
                               'source': f'{inspection}: '
                                         + ('no exact duplicate rows' if not s['duplicate_rows']
                                            else f'{s["duplicate_rows"]} rows repeat an earlier '
                                                 f'row')}
    return {
        'schema': 'hypotrail.case/1',
        'id': 'uci-bank-marketing-full-v1',
        'title': 'Bank Marketing (full file, in time order) · UCI',
        'description': 'Who should be contacted when the team cannot call everyone? The full '
                       'record of the telephone campaigns of a Portuguese bank, May 2008 to '
                       'November 2010; the final test is the latest fifth of the calls.',
        'provenance': provenance,
        'dataset': {'path': DATA, 'format': 'csv', 'sep': ';', 'encoding': 'utf-8',
                    'decimal': '.', 'header': True, 'sha256': sha, 'rows': s['rows'],
                    'columns': len(s['header']), 'quotechar': '"'},
        'target': dict(base['target']),
        'row_key': {'rule': 'source_line', 'format': 'L<line>',
                    'description': 'Physical 1-based line number in bank-full.csv; the header '
                                   'is line 1, so the first data row is L2. The key is anchored '
                                   'to the dataset sha256.'},
        'facts': facts,
        'variables': base['variables'],
        'special_values': base['special_values'],
        'structure': structure,
        'task': 'binary',
        'prior_exposure': [
            {'value': 'A widely used public dataset (UCI since 2012, Kaggle, tutorials and '
                      'papers): its rows are not unseen, and a language model has likely read '
                      'analyses of it, among them the strength of duration.',
             'status': 'observed', 'source': 'Public availability since 2012'},
            {'value': f'The {s["sample_rows"]} rows of bank.csv are rows of this file; the '
                      f'Hypotrail tutorial published results on them (use-cases/bank-marketing). '
                      f'Those rows are not unseen.',
             'status': 'observed', 'source': 'Fact data_contains_sample'},
        ],
        'prior_exposed_rows': {
            'path': PRIOR_ROWS, 'sha256': hashlib.sha256(prior).hexdigest(), 'rows': n_prior,
            'match': 'row_key', 'status': 'observed',
            'source': f'Fact data_contains_sample; {PRIOR_ROWS} lists the row keys of the '
                      f'bank-full.csv records that are bank.csv records (exact record match '
                      f'after csv parsing, build_case.py). They stay development rows: the '
                      f'sealed final test holds none of them.'},
        'order': {'by': 'line', 'direction': 'ascending', 'status': 'documented_fact',
                  'source': f'{NAMES}:31: bank-full.csv with all examples, ordered by date '
                            f'(from May 2008 to November 2010)'},
        'scenario_defaults': {
            'capacity_share': {
                'value': 0.1, 'status': 'scenario_assumption',
                'source': 'Teaching scenario: the call team can contact one client in ten. A '
                          'real team would give its own figure.'},
        },
        'analysis_contract': {
            'schema': 'hypotrail.analysis/1',
            'scenario_id': 'bank-full-retrospective-v1',
            'intended_use': 'retrospective_comparison',
            'row_unit': 'client campaign contact',
            'population': 'Published Bank Marketing campaigns, excluding previously exposed final rows',
            'prediction_statement': 'Compare pre-call targeting retrospectively',
            'timing': {'prediction_order': {'by': 'line', 'status': 'documented_fact',
                                           'source': f'{NAMES}:31: examples ordered by date'},
                       'outcome_available_order': None, 'scale': 'ordinal'},
            'dependencies': {'kind': 'unknown', 'group_column': None, 'group_goal': None,
                             'status': 'unknown',
                             'source': 'README.md: no complete client history or outcome-availability clock'},
            'permitted_claims': ['retrospective_association'],
        },
    }


def render(document: dict) -> str:
    return HEADER + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--verify', action='store_true')
    parser.add_argument('--out', type=Path)
    args = parser.parse_args(argv)
    data = (HERE / DATA).read_bytes()
    if args.verify:
        problems = verify(data)
        s = inspect(data)
        print(f'sha256 {hashlib.sha256(data).hexdigest()}')
        print(f'rows {s["rows"]}, columns {len(s["header"])}, y {dict(s["labels"])}, '
              f'duplicate rows {s["duplicate_rows"]}, bank.csv rows {s["sample_rows"]} '
              f'(not contained: {s["sample_not_contained"]}), month runs '
              f'{len(s["month_runs"])} from {s["month_runs"][0]} to {s["month_runs"][-1]}')
        for p in problems:
            print('MISMATCH', p)
        return 1 if problems else 0
    text = render(case_document(data))
    prior = prior_rows_text(data)
    if args.check:
        prior_path = HERE / PRIOR_ROWS
        same = (HERE / 'case.yaml').read_text(encoding='utf-8') == text and \
            prior_path.is_file() and prior_path.read_text(encoding='utf-8') == prior
        print('case.yaml is up to date' if same else 'case.yaml differs from a fresh generation')
        return 0 if same else 1
    target = args.out or HERE
    if args.out:
        (target / 'data').mkdir(parents=True, exist_ok=True)
        for name in (DATA, NAMES):
            shutil.copyfile(HERE / name, target / name)
    (target / PRIOR_ROWS).write_text(prior, encoding='utf-8')
    (target / 'case.yaml').write_text(text, encoding='utf-8')
    print(f'wrote {target / "case.yaml"}')
    return 0


if __name__ == '__main__':
    sys.exit(main())
