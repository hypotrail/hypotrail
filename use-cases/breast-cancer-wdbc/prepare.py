"""Materialize the Breast Cancer Wisconsin (Diagnostic) case from the installed scikit-learn.

The data are not committed to this repository: neither the scikit-learn package files
nor its licence state the terms under which the data may be redistributed (see
README.md). This script copies them from the installed package, without any download:

* ``data/wdbc.csv``: the 569 rows of ``sklearn/datasets/data/breast_cancer.csv`` with a
  header of snake_case feature names and the class written as ``malignant`` or
  ``benign`` (the package file codes it 0 and 1, in the order of its first line);
* ``case.yaml``: the ``hypotrail.case/1`` adapter, with the sha256 of that CSV.

``case.yaml`` is committed and generated by this script; edit the script, never the
YAML. The CSV is git-ignored. Usage (from the repository root)::

    uv run --project framework python use-cases/breast-cancer-wdbc/prepare.py            # here
    uv run --project framework python use-cases/breast-cancer-wdbc/prepare.py --out DIR  # a copy
    uv run --project framework python use-cases/breast-cancer-wdbc/prepare.py --check

``--out DIR`` writes a complete case folder (``case.yaml`` and ``data/``) in DIR, for
tests. ``--check`` exits 1 when the committed ``case.yaml`` differs from a fresh
generation (for example after a scikit-learn upgrade changed the bundled file). No model
is trained.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
from importlib import resources
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
DATA = 'data/wdbc.csv'
DESCR = 'sklearn/datasets/descr/breast_cancer.rst'
PACKAGE_FILE = 'sklearn/datasets/data/breast_cancer.csv'
TARGET = 'diagnosis'
# The ten measurements of descr lines 13-22, each as a mean, a standard error, and a
# "worst" value (descr lines 24-27).
MEASURES = [
    ('radius', 'mean of distances from center to points on the perimeter', 13),
    ('texture', 'standard deviation of gray-scale values', 14),
    ('perimeter', 'perimeter of the nucleus', 15),
    ('area', 'area of the nucleus', 16),
    ('smoothness', 'local variation in radius lengths', 17),
    ('compactness', 'perimeter^2 / area - 1.0', 18),
    ('concavity', 'severity of concave portions of the contour', 19),
    ('concave_points', 'number of concave portions of the contour', 20),
    ('symmetry', 'symmetry of the nucleus', 21),
    ('fractal_dimension', '"coastline approximation" - 1', 22),
]
STATS = [('mean', 'mean over the nuclei of the image'),
         ('error', 'standard error over the nuclei of the image'),
         ('worst', 'mean of the three largest values over the nuclei of the image')]
HEADER = ('# Generated by use-cases/breast-cancer-wdbc/prepare.py from the installed scikit-learn.\n'
          '# Do not edit by hand: change prepare.py and regenerate with\n'
          '#   uv run --project framework python use-cases/breast-cancer-wdbc/prepare.py\n'
          '# A case states facts and assumptions; human decisions live in study state.\n')


def feature_names() -> list[str]:
    out = []
    for stat, _ in STATS:
        for measure, _, _ in MEASURES:
            out.append(f'{stat}_{measure}' if stat != 'error' else f'{measure}_error')
    return out


def _package_bytes() -> bytes:
    return resources.files('sklearn.datasets.data').joinpath('breast_cancer.csv').read_bytes()


def dataset_bytes() -> tuple[bytes, bytes]:
    """``(csv bytes, package file bytes)``. The values are copied as written."""
    raw = _package_bytes()
    lines = raw.decode('ascii').splitlines()
    n_rows, n_features, *labels = lines[0].split(',')
    if (n_rows, n_features, labels) != ('569', '30', ['malignant', 'benign']):
        raise SystemExit(f'Unexpected first line of {PACKAGE_FILE}: {lines[0]!r}')
    from sklearn.datasets import load_breast_cancer
    expected = [str(n).replace(' ', '_') for n in load_breast_cancer().feature_names]
    if expected != feature_names():
        raise SystemExit(f'Feature names differ from the package: {expected}')
    out = [','.join(feature_names() + [TARGET])]
    for line in lines[1:]:
        fields = line.split(',')
        if len(fields) != 31 or fields[-1] not in ('0', '1'):
            raise SystemExit(f'Unexpected row in {PACKAGE_FILE}: {line!r}')
        out.append(','.join(fields[:-1] + [labels[int(fields[-1])]]))
    if len(out) - 1 != int(n_rows):
        raise SystemExit(f'{PACKAGE_FILE} has {len(out) - 1} rows, its first line says {n_rows}')
    return ('\n'.join(out) + '\n').encode('ascii'), raw


def _sha(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _available(source: str) -> dict:
    return {'value': 'available_at_prediction', 'status': 'scenario_assumption',
            'source': source}


