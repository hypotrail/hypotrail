#!/usr/bin/env python3
"""Requirement-id coverage of the advanced companion, generated from the tests (WP-I).

    python3 scripts/companion_coverage.py            print the Markdown table
    python3 scripts/companion_coverage.py --write    rewrite the block in V0.1-CHECKLIST.md

Every requirement id of docs/specs/COMPANION-ADVANCED.md (``OV-3``, ``INV-12``, ...) is
looked up in the companion's test sources (clients/vscode-companion/test, without the
fixtures, and the engine's companion tests). An id is covered by a test file that names it
(in a test name, a docstring, or a comment next to the assertion). The table lists the
files per id. ``clients/vscode-companion/test/test_requirement_coverage.py`` fails when an
id has no test or when the checklist block is not the generated one.

Standard library only; it reads files and writes nothing unless ``--write`` is given.
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
SPEC = REPO / 'docs' / 'specs' / 'COMPANION-ADVANCED.md'
CHECKLIST = REPO / 'docs' / 'acceptance' / 'V0.1-CHECKLIST.md'
START = '<!-- companion-coverage:start (generated by scripts/companion_coverage.py) -->'
END = '<!-- companion-coverage:end -->'
ID = re.compile(r'\b(INV|OV|HE|ST|DC|RQ|DH|ED|EV|WI|LE|HO|SR|AB|RV|A11Y)-([0-9]+)\b')
# A Python test name carries the id in lower case without the dash: ``test_ev3_...``.
TEST_NAME_ID = re.compile(r'\btest_(inv|ov|he|st|dc|rq|dh|ed|ev|wi|le|ho|sr|ab|rv|a11y)([0-9]+)_')


def requirement_ids() -> list[str]:
    ids = {f'{m.group(1)}-{m.group(2)}' for m in ID.finditer(SPEC.read_text(encoding='utf-8'))}
    order = ['INV', 'OV', 'HE', 'ST', 'DC', 'RQ', 'DH', 'ED', 'EV', 'WI', 'LE', 'HO', 'SR', 'AB', 'RV', 'A11Y']
    return sorted(ids, key=lambda i: (order.index(i.split('-')[0]), int(i.split('-')[1])))


def test_files() -> list[Path]:
    client = REPO / 'clients' / 'vscode-companion' / 'test'
    files = [p for p in sorted(client.glob('*')) if p.suffix in ('.js', '.py')
             and p.name not in ('conftest.py', 'test_requirement_coverage.py')]
    engine = REPO / 'framework' / 'tests' / 'study'
    files += sorted(engine.glob('test_companion*.py')) + sorted(engine.glob('test_contract_companion*.py'))
    return files


def coverage() -> dict[str, list[str]]:
    found: dict[str, set[str]] = {i: set() for i in requirement_ids()}
    for path in test_files():
        text = path.read_text(encoding='utf-8')
        hits = [f'{m.group(1)}-{m.group(2)}' for m in ID.finditer(text)]
        hits += [f'{m.group(1).upper()}-{m.group(2)}' for m in TEST_NAME_ID.finditer(text)]
        for rid in hits:
            if rid in found:
                found[rid].add(path.relative_to(REPO).as_posix())
    return {k: sorted(v) for k, v in found.items()}


def table() -> str:
    rows = ['| Requirement | Test files that name it |', '|---|---|']
    for rid, files in coverage().items():
        names = ', '.join(f'`{Path(f).name}`' for f in files) or '**none**'
        rows.append(f'| {rid} | {names} |')
    return '\n'.join(rows)


def block() -> str:
    return f'{START}\n{table()}\n{END}'


def main(argv: list[str]) -> int:
    if '--write' in argv:
        text = CHECKLIST.read_text(encoding='utf-8')
        if START in text:
            head, rest = text.split(START, 1)
            tail = rest.split(END, 1)[1]
            text = head + block() + tail
        else:
            raise SystemExit(f'{CHECKLIST} has no coverage block; add the markers first')
        CHECKLIST.write_text(text, encoding='utf-8')
    else:
        print(table())
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
