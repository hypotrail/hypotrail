"""Prototype generator for ``study_generated.py`` and ``workbench.py``.

Notebook sources are produced with Marimo's own code generator
(``marimo._ast.codegen.generate_filecontents``, an internal API of the pinned
0.25.1 release) so that the bytes we write are the bytes the Marimo editor
would write back when it saves an unmodified notebook.

Preservation rules exercised by the spike:

* ``study_generated.py`` is regenerated on every render. If its bytes differ
  from the sha256 recorded in the manifest, the file is first copied byte for
  byte to ``study_generated.user-edits-<rev>.py`` (``<rev>`` is the revision
  the edited file was generated at), then regenerated.
* ``workbench.py`` is created once and never written again. When the
  workbench template version increases, ``workbench.candidate.py`` is
  written next to it instead.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
from pathlib import Path
from typing import Any

from marimo._ast.app_config import _AppConfig
from marimo._ast.cell import CellConfig
from marimo._ast.codegen import generate_filecontents

from . import guard, read

GENERATED = "notebooks/study_generated.py"
WORKBENCH = "notebooks/workbench.py"
CANDIDATE = "notebooks/workbench.candidate.py"
WORKBENCH_TEMPLATE_VERSION = 1
STUDY_TEMPLATE_VERSION = 1


_GENERATED_WITH = re.compile(rb'^__generated_with = "[^"\n]*"$', re.MULTILINE)


def sha256(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def edit_check_sha256(data: bytes) -> str:
    """Hash used to detect user edits.

    Only the ``__generated_with`` version stamp is ignored: a newer Marimo
    rewrites it on save (as marimo/_utils/generated_with.py does for its own
    reload check), and that is not a user edit. Every other byte counts.
    """
    return sha256(_GENERATED_WITH.sub(b'__generated_with = ""', data))


def _atomic_write(path: Path, data: bytes) -> None:
    guard.assert_writable()
    tmp = path.with_name(f".{path.name}.tmp")
    with open(tmp, "wb") as handle:
        handle.write(data)
        handle.flush()
        os.fsync(handle.fileno())
    os.replace(tmp, path)


def _create_exclusive(path: Path, data: bytes) -> None:
    guard.assert_writable()
    with open(path, "xb") as handle:
        handle.write(data)


def _setup_code(extra_imports: str = "") -> str:
    return (
        "import os\n"
        "\n"
        'os.environ["HYPOTRAIL_READ_ONLY"] = "1"\n'
        "from pathlib import Path\n"
        "\n"
        "import marimo as mo\n"
        f"from prototype import read{extra_imports}\n"
        "\n"
        "STUDY_DIR = Path(__file__).resolve().parents[1]"
    )


def _codegen(header: str, cells: list[tuple[str, str]]) -> str:
    names = [name for name, _ in cells]
    codes = [code for _, code in cells]
    return generate_filecontents(
        codes,
        names,
        [CellConfig() for _ in cells],
        config=_AppConfig(),
        header_comments=header,
    )


def generate_study_source(view: dict[str, Any]) -> str:
    revision = view["revision"]
    result_ids = {step["id"]: step["result_id"] for step in view["steps"] if step["result_id"]}
    header = (
        f"# Generated by Hypotrail (spike prototype) at revision {revision}. Do not edit.\n"
        "# A modified copy is preserved as study_generated.user-edits-<rev>.py on the next render.\n"
        f"# template_version = {STUDY_TEMPLATE_VERSION}"
    )
    setup = (
        _setup_code()
        + f"\n\nGENERATED_REVISION = {revision!r}\n"
        + f"RESULT_IDS = {json.dumps(result_ids, sort_keys=True)}"
    )
    cells: list[tuple[str, str]] = [
        ("setup", setup),
        ("load_view", "view = read.open(STUDY_DIR)"),
        ("banner", "mo.md(read.banner(view, GENERATED_REVISION))"),
    ]
    for index, step in enumerate(view["steps"], start=1):
        title = f"## {index}. {step['title']}\n\n**{step['concept']}.** {step['question']}"
        if step["result_id"]:
            body = (
                "mo.vstack(\n"
                "    [\n"
                f"        mo.md({title!r}),\n"
                f"        mo.Html(read.numbers_html(view, RESULT_IDS[{step['id']!r}])),\n"
                f"        mo.md(read.source_block(view, RESULT_IDS[{step['id']!r}])),\n"
                "    ]\n"
                ")"
            )
        else:
            pending = title + "\n\nNot executed yet."
            body = f"mo.md({pending!r})"
        cells.append((f"step_{step['id']}", body))
    return _codegen(header, cells)


def generate_workbench_source(template_version: int) -> str:
    header = (
        f"# Hypotrail workbench (spike prototype), template_version = {template_version}.\n"
        "# Created once. Hypotrail never overwrites this file; experiments here are not tracked."
    )
    cells = [
        ("setup", _setup_code(", policy")),
        ("load_view", "view = read.open(STUDY_DIR)"),
        ("threshold_slider", (
            "threshold = mo.ui.slider(\n"
            "    start=0.05, stop=0.95, step=0.05, value=0.5, label=\"Experiment, not adopted\"\n"
            ")\n"
            "threshold"
        )),
        ("experiment", (
            "_rid = view.data[\"current\"][\"predictions\"]\n"
            "_y = view.value(_rid, \"y\")\n"
            "_score = view.value(_rid, \"score\")\n"
            "_adopted = view.data[\"decisions\"][\"policy\"][\"value\"][\"threshold\"]\n"
            "mo.md(read.compare_md(policy.evaluate(_y, _score, threshold.value), "
            "policy.evaluate(_y, _score, _adopted)))"
        )),
        ("your_notes", (
            "mo.md(\n"
            "    \"\"\"\n"
            "## Your notes\n"
            "\n"
            "Write your observations here. Hypotrail does not read or track this notebook.\n"
            "\"\"\"\n"
            ")"
        )),
    ]
    if template_version >= 2:
        cells.insert(4, ("template_v2_hint", "mo.md(\"Template version 2 adds this hint.\")"))
    return _codegen(header, cells)


def _load_manifest(study: Path) -> dict[str, Any]:
    path = study / ".hypotrail" / "artifacts.json"
    if path.exists():
        return json.loads(path.read_text(encoding="utf-8"))
    return {"artifacts": {}}


def _preserve_user_edits(study: Path, record: dict[str, Any] | None) -> str | None:
    path = study / GENERATED
    if not path.exists():
        return None
    current = path.read_bytes()
    if record is not None and edit_check_sha256(current) == record["edit_check_sha256"]:
        return None
    rev = record["revision"] if record is not None else "unknown"
    base = f"study_generated.user-edits-{rev}"
    target = path.with_name(f"{base}.py")
    counter = 2
    while target.exists():
        target = path.with_name(f"{base}-{counter}.py")
        counter += 1
    _create_exclusive(target, current)
    return f"notebooks/{target.name}"


def render(study: Path, workbench_template_version: int = WORKBENCH_TEMPLATE_VERSION) -> dict[str, Any]:
    """Regenerate notebooks and update the manifest. Returns a report."""
    guard.assert_writable()
    study = Path(study)
    view = read.build(study)
    manifest = _load_manifest(study)
    artifacts = manifest["artifacts"]
    report: dict[str, Any] = {"preserved": None, "workbench": "kept", "candidate": None}

    record = artifacts.get(GENERATED)
    preserved = _preserve_user_edits(study, record)
    data = generate_study_source(view).encode("utf-8")
    _atomic_write(study / GENERATED, data)
    history = list(record.get("user_edits_preserved", [])) if record else []
    if preserved:
        history.append(preserved)
        report["preserved"] = preserved
    artifacts[GENERATED] = {
        "revision": view["revision"], "status": "ok", "sha256": sha256(data),
        "edit_check_sha256": edit_check_sha256(data),
        "generated": True, "template_version": STUDY_TEMPLATE_VERSION,
        "user_edits_preserved": history,
    }

    workbench = study / WORKBENCH
    wb_record = artifacts.get(WORKBENCH)
    if not workbench.exists():
        wb_data = generate_workbench_source(workbench_template_version).encode("utf-8")
        _create_exclusive(workbench, wb_data)
        artifacts[WORKBENCH] = {"generated": False, "template_version": workbench_template_version,
                                "sha256_at_creation": sha256(wb_data), "candidate": None}
        report["workbench"] = "created"
    elif wb_record is not None and workbench_template_version > wb_record["template_version"]:
        cand = generate_workbench_source(workbench_template_version).encode("utf-8")
        _atomic_write(study / CANDIDATE, cand)
        wb_record["candidate"] = {"path": CANDIDATE, "template_version": workbench_template_version,
                                  "sha256": sha256(cand)}
        report["candidate"] = CANDIDATE

    manifest_bytes = (json.dumps(manifest, indent=2, sort_keys=True) + "\n").encode("utf-8")
    _atomic_write(study / ".hypotrail" / "artifacts.json", manifest_bytes)
    return report
