"""The scikit-learn cases (M3 generality): committed adapters, data materialized locally.

``use-cases/breast-cancer-wdbc`` (binary) and ``use-cases/diabetes`` (regression without a
time column) commit a ``case.yaml`` generated by their ``prepare.py`` and never the data,
whose redistribution terms the package does not state. These tests materialize them in
temporary folders only.
"""
from __future__ import annotations

import subprocess
import sys

import pytest
import yaml

from mlkit.study import case as c, data

import flowkit as fk

CASES = {'wdbc': fk.WDBC, 'diabetes': fk.DIABETES}


@pytest.mark.parametrize('name', sorted(CASES))
def test_committed_case_is_the_fresh_generation_and_valid(name):
    case_dir = CASES[name]
    proc = subprocess.run([sys.executable, str(case_dir / 'prepare.py'), '--check'],
                          capture_output=True, text=True, timeout=120)
    assert proc.returncode == 0, proc.stderr
    document = yaml.safe_load((case_dir / 'case.yaml').read_text(encoding='utf-8'))
    c.check_document(document)
    assert c.unsupported_capabilities(document) == [] and c.limitations(document) == []
    assert 'confirm' not in (case_dir / 'case.yaml').read_text(encoding='utf-8').lower()
    assert document['provenance']['license'].startswith('Not stated in the scikit-learn')


def test_data_are_ignored_and_not_tracked():
    ignore = (fk.REPO / '.gitignore').read_text(encoding='utf-8')
    for case_dir in CASES.values():
        assert f'/use-cases/{case_dir.name}/data/' in ignore
        proc = subprocess.run(['git', 'ls-files', '--', f'use-cases/{case_dir.name}'],
                              capture_output=True, text=True, cwd=fk.REPO, timeout=60)
        assert proc.returncode == 0, proc.stderr
        assert not [p for p in proc.stdout.splitlines() if '/data/' in p]


def test_check_layout_accepts_an_absent_materialized_dataset_only(tmp_path, monkeypatch):
    import importlib.util
    spec = importlib.util.spec_from_file_location('check_layout_materialized',
                                                  fk.REPO / 'scripts/check_layout.py')
    layout = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(layout)
    case_dir = fk.materialize(fk.DIABETES, tmp_path / 'use-cases' / 'diabetes')
    (case_dir / 'prepare.py').write_text('# copies the data\n')
    monkeypatch.setattr(layout, 'ROOT', tmp_path)
    errors, absent = [], []
    assert layout.check_cases(errors, absent) == 1 and errors == [] and absent == []
    (case_dir / 'data/diabetes.csv').unlink()
    assert layout.check_cases(errors, absent) == 1 and errors == []
    assert absent == ['diabetes/data/diabetes.csv (run diabetes/prepare.py)']
    (case_dir / 'data/diabetes.csv').write_text('age\n1\n')
    assert layout.check_cases(errors) == 1
    assert errors == ['Case dataset fingerprint mismatch: diabetes']


@pytest.mark.parametrize('name, task, rows, columns', [('wdbc', 'binary', 569, 31),
                                                       ('diabetes', 'regression', 442, 11)])
def test_materialized_case_loads_with_row_keys(name, task, rows, columns, tmp_path):
    case = c.load_case(fk.materialize(CASES[name], tmp_path / name))
    assert case.task == task
    dataset = data.load_dataset(case)
    assert dataset.frame.shape == (rows, columns)
    assert dataset.frame.index[0] == 'L2' and data.content_duplicates(dataset.index) == []
    assert case.dataset['sha256'] == yaml.safe_load(
        (CASES[name] / 'case.yaml').read_text())['dataset']['sha256']
    if task == 'binary':
        assert set(dataset.frame[case.target_column]) == {'malignant', 'benign'}
    else:
        assert dataset.frame[case.target_column].dtype.kind == 'i'
