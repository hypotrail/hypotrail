def _rule(text: str, n: int) -> Flat:
    """Rule ``n`` of the non-negotiable rules of ``CLAUDE.md.in``."""
    return Flat(text.split(f'\n{n}. **', 1)[1].split(f'\n{n + 1}. **', 1)[0])


