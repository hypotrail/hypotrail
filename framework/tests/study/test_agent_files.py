def test_init_installs_both_agents_with_the_exact_invocation(study):
    target, payload = study
    info = payload['agent_instructions']
    assert info['status'] == 'copied' and info['skipped_existing'] == []
    assert set(info['copied']) == CLAUDE_TARGETS | COPILOT_TARGETS
    record = json.loads((target / '.hypotrail' / af.AGENT_FILE).read_text())
    assert record['schema'] == af.SCHEMA and record['study'] == str(target.resolve())
    assert record['cli']['shell'] == info['cli'] == shlex.join(record['cli']['argv'])
    invocation = f'{record["cli"]["shell"]} status --json --study {shlex.quote(str(target.resolve()))}'
    for rel in CLAUDE_TARGETS | COPILOT_TARGETS:
        text = (target / rel).read_text()
        assert '{{' not in text and '}}' not in text, rel
        assert record['cli']['shell'] in text, rel
    claude = (target / 'CLAUDE.md').read_text()
    assert invocation in claude
    assert '.claude/skills/hypotrail-study/SKILL.md' in claude
    copilot = (target / '.github/copilot-instructions.md').read_text()
    assert copilot.startswith('<!-- Generated by hypotrail init') and 'Not tested' in copilot
    assert '.github/skills/hypotrail-study/SKILL.md' in copilot
    for rel in ('.github/skills/hypotrail-study/SKILL.md',
                '.github/prompts/hypotrail-resume.prompt.md'):
        text = (target / rel).read_text()
        assert text.startswith('---\n'), rel                # front matter stays first
        assert 'Not tested with GitHub Copilot' in text.split('\n---\n', 1)[1].splitlines()[0]
    assert 'mode: agent' in (target / '.github/prompts/hypotrail-resume.prompt.md').read_text()
    skill = (target / '.claude/skills/hypotrail-study/SKILL.md').read_text()
    # D10: the glossary is copied into the study; the instructions point there, never into
    # the engine's source tree (agents may not read it).
    glossary = target.resolve() / af.STUDY_GLOSSARY
    assert skill.startswith('---\nname: hypotrail-study\n') and str(glossary) in skill
    assert str(af.GLOSSARY) not in skill and str(af.GLOSSARY.parent) not in claude
    assert af.GLOSSARY.is_file() and glossary.read_bytes() == af.GLOSSARY.read_bytes()
    assert info['glossary'] == af.STUDY_GLOSSARY and record['glossary'] == str(glossary)


