def test_no_template_is_stored_under_a_name_an_agent_loads():
    """Developer sessions in this repository must never load the study agent's rules."""
    stored = [p.relative_to(af.SOURCE) for p in af.SOURCE.rglob('*')]
    loaded = [str(p) for p in stored if set(p.parts) & set(af.LOADED_NAMES)]
    assert loaded == []
    assert set(af.templates()) == set(af.TARGETS)          # every template is mapped


def test_the_name_mapping():
    assert af.default_target('dot-claude/commands/x.md') == '.claude/commands/x.md'
    assert af.default_target('dot-github/prompts/y.prompt.md') == '.github/prompts/y.prompt.md'
