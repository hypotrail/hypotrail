CLAUDE_TARGETS = {'CLAUDE.md', '.claude/skills/hypotrail-study/SKILL.md',
                  '.claude/commands/hypotrail-resume.md'}
COPILOT_TARGETS = {'.github/copilot-instructions.md', '.github/skills/hypotrail-study/SKILL.md',
                   '.github/prompts/hypotrail-resume.prompt.md'}


def test_no_template_is_stored_under_a_name_an_agent_loads():
    """Developer sessions in this repository must never load the study agent's rules."""
    stored = [p.relative_to(af.SOURCE) for p in af.SOURCE.rglob('*')]
    loaded = [str(p) for p in stored if set(p.parts) & set(af.LOADED_NAMES)]
    assert loaded == []
    assert set(af.templates()) == set(af.TARGETS)          # every template is mapped


def test_the_name_mapping():
    assert af.default_target('dot-claude/commands/x.md') == '.claude/commands/x.md'
    assert af.default_target('dot-github/prompts/y.prompt.md') == '.github/prompts/y.prompt.md'
    assert af.default_target('CLAUDE.md.in') == 'CLAUDE.md'
    assert af.default_target('notes/dot.txt') == 'notes/dot.txt'
    mapped = {t for rel in af.TARGETS for t, _ in af.targets(rel)}
    assert mapped == CLAUDE_TARGETS | COPILOT_TARGETS


@pytest.fixture
def study(tmp_path, synthetic_case_dir, monkeypatch):
    monkeypatch.delenv(af.CLI_ENV, raising=False)
    target = tmp_path / 'study'
    payload = cmd.init(synthetic_case_dir, target).payload
    return target, payload


def test_init_installs_both_agents_with_the_exact_invocation(study):
    target, payload = study
    info = payload['agent_instructions']
    assert info['status'] == 'copied' and info['skipped_existing'] == []
    assert set(info['copied']) == CLAUDE_TARGETS | COPILOT_TARGETS
    record = json.loads((target / '.hypotrail' / af.AGENT_FILE).read_text())
    assert record['schema'] == af.SCHEMA and record['study'] == str(target.resolve())
    assert record['cli']['shell'] == info['cli'] == shlex.join(record['cli']['argv'])
    invocation = f'{record["cli"]["shell"]} status --json --study {shlex.quote(str(target.resolve()))}'
    for rel in CLAUDE_TARGETS | COPILOT_TARGETS:
        text = (target / rel).read_text()
        assert '{{' not in text and '}}' not in text, rel
        assert record['cli']['shell'] in text, rel
    claude = (target / 'CLAUDE.md').read_text()
    assert invocation in claude
    assert '.claude/skills/hypotrail-study/SKILL.md' in claude
    copilot = (target / '.github/copilot-instructions.md').read_text()
    assert copilot.startswith('<!-- Generated by hypotrail init') and 'Not tested' in copilot
    assert '.github/skills/hypotrail-study/SKILL.md' in copilot
    for rel in ('.github/skills/hypotrail-study/SKILL.md',
                '.github/prompts/hypotrail-resume.prompt.md'):
        text = (target / rel).read_text()
        assert text.startswith('---\n'), rel                # front matter stays first
        assert 'Not tested with GitHub Copilot' in text.split('\n---\n', 1)[1].splitlines()[0]
    assert 'mode: agent' in (target / '.github/prompts/hypotrail-resume.prompt.md').read_text()
    skill = (target / '.claude/skills/hypotrail-study/SKILL.md').read_text()
    assert skill.startswith('---\nname: hypotrail-study\n') and str(af.GLOSSARY) in skill
    assert af.GLOSSARY.is_file()


def test_the_recorded_invocation_runs_status(study):
    target, _ = study
    record = json.loads((target / '.hypotrail' / af.AGENT_FILE).read_text())
    proc = subprocess.run([*record['cli']['argv'], 'status', '--json', '--study', str(target)],
                          capture_output=True, text=True, cwd=target, env=fk.env(),
                          timeout=300)
    assert proc.returncode == 0, proc.stderr
    assert json.loads(proc.stdout)['view']['revision'] == 1


def test_existing_files_are_never_overwritten(tmp_path, synthetic_case_dir, monkeypatch):
    monkeypatch.delenv(af.CLI_ENV, raising=False)
    target = tmp_path / 'study'
    target.mkdir()
    (target / 'CLAUDE.md').write_text('my own rules\n')
    info = cmd.init(synthetic_case_dir, target).payload['agent_instructions']
    assert (target / 'CLAUDE.md').read_text() == 'my own rules\n'
    assert info['skipped_existing'] == ['CLAUDE.md']
    assert 'CLAUDE.md' not in info['copied'] and '.github/copilot-instructions.md' in info['copied']
    again = af.install(target)
    assert again['status'] == 'kept_existing' and again['copied'] == []


def test_cli_override_is_recorded(tmp_path, synthetic_case_dir, monkeypatch):
    monkeypatch.setenv(af.CLI_ENV, '/opt/hyp/bin/hypotrail')
    target = tmp_path / 'study'
    cmd.init(synthetic_case_dir, target)
    record = json.loads((target / '.hypotrail' / af.AGENT_FILE).read_text())
    assert record['cli'] == {'argv': ['/opt/hyp/bin/hypotrail'],
                             'shell': '/opt/hyp/bin/hypotrail', 'how': 'override'}
    assert '/opt/hyp/bin/hypotrail status --json' in (target / 'CLAUDE.md').read_text()


def test_instructions_name_only_real_decisions_activities_and_commands():
    """The rules quote the contract; they must not drift from it."""
    text = (af.SOURCE / 'CLAUDE.md.in').read_text()
    for d in st.DECISION_IDS:
        assert f'`{d}`' in text, d
    for a in ('split', 'eda.target_rate', 'eda.special_values', 'eda.rate_by', 'fit.baseline',
              'fit.logistic', 'policy.evaluate'):
        assert f'`{a}' in text and a in act.CLI_NAMES, a
    for phrase in ('status --json', '--user-words', '--restatement', 'check --text -',
                   'stale_revision', '--request-id', 'garde ça', 'not supported in v0.1'):
        assert phrase in text, phrase
    resume = (af.SOURCE / 'dot-claude/commands/hypotrail-resume.md').read_text()
    assert 'status --json' in resume and 'five lines' in resume


def test_unknown_placeholders_are_refused():
    with pytest.raises(ValueError, match='NOPE'):
        af.render('{{NOPE}}', flavour=af.CLAUDE, values={}, source='x.md')
    assert os.path.basename(af.SKILL_PATHS[af.CLAUDE]) == 'SKILL.md'
    assert Path(af.SKILL_PATHS[af.COPILOT]).parts[0] == '.github'
