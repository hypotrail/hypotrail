"""Strong, standard baselines, generated from the registry and run before any exploration.

    python -m mlkit.baselines            # generate model/baselines/<name>.py, then run each one
    python -m mlkit.baselines --dry-run  # generate only, run nothing

The human lists them in frame.yaml:

    spec:
      baselines: [splines_logit, monotone_hgb, ebm, autogluon]
      baselines_autogluon: {time_limit: 120, presets: medium_quality}   # optional; best_quality for a real project

Why: agents that start from a generic boosting found about 60 % of the findable gain. A floor
of well-known strong models, built the same way on every project, is cheaper than hoping the
agent rediscovers them. They are REFERENCES, not a starting point: each is an exploratory run, so
under selection_rule mean_rank_all it is a member of the final rank average like any other run.
No « best baseline » is named (an agent told to start from it stayed locked in a model that tied on
the backtest and lost on the holdout).

`autogluon`: AutoGluon (autogluon.tabular) wrapped by mlkit.automl.AutoGluonClassifier, time limit
and presets fixed in the frame, written into the generated file (code hash). Skipped with a clear
message when autogluon is not importable.

Every generated file declares FAMILY (mlkit.ensemble groups members by family).

Each baseline is an ordinary pipeline file (FEATURES + build(), self-contained sklearn code, so
its code hash covers everything it does). Columns: every `available: origination` column of
features.yaml that is not excluded and is present in data/dev; numeric if `contract.type` is
numeric (or, without a contract type, if the dev column is numeric), categorical otherwise.

Each file then goes through `mlkit.run` (same function, same controls: gate, open stops, I5, D6,
D1, budget checked before, stops after), counted as one comparison, note
« baseline automatic <name> ». Idempotent: a baseline already in the registry as an
exploratory run under the same frame hash and the same code hash is not run again.

Exit codes: 0 ok · 9 frame lists an unknown baseline · 10 role not allowed ·
other codes are those of mlkit.run (2, 3, 5, 6, 7, 8), returned as soon as one stops the sequence.
"""
from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

import pandas as pd

from . import config, core

KNOWN = ("splines_logit", "monotone_hgb", "ebm", "autogluon")
AUTOGLUON_DEFAULTS = {"time_limit": 120, "presets": "medium_quality"}
ALLOWED_ROLES = {"explorer", "human"}
BASELINE_DIR = "model/baselines"

HEADER = '''"""Automatic baseline {name} — GENERATED by `python -m mlkit.baselines`; do not edit.

{doc}
Columns: all features.yaml entries available at origination, not excluded, and present in data/dev
({n_num} numeric, {n_cat} categorical). To improve it, copy this file to model/<name>.py.
"""
'''

COLUMNS = '''
FAMILY = {family!r}   # mlkit.ensemble: family of this member in rank averaging
NUMERIC = {num!r}
CATEGORICAL = {cat!r}
FEATURES = NUMERIC + CATEGORICAL
'''

SPLINES_LOGIT = HEADER + '''from sklearn.compose import ColumnTransformer
from sklearn.impute import MissingIndicator, SimpleImputer
from sklearn.linear_model import LogisticRegression
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OneHotEncoder, QuantileTransformer, SplineTransformer
''' + COLUMNS + '''

def build():
    numeric = make_pipeline(
        SimpleImputer(strategy="median"),
        # rank first, then uniform knots = knots at quantiles, robust to tied values (counts, grades)
        QuantileTransformer(n_quantiles=200, subsample=100_000, random_state=0),
        SplineTransformer(n_knots=5, degree=3, knots="uniform", extrapolation="constant"),
    )
    categorical = make_pipeline(
        SimpleImputer(strategy="constant", fill_value="__manquant__"),
        OneHotEncoder(handle_unknown="infrequent_if_exist", min_frequency=0.01, sparse_output=False),
    )
    parts = [("num", numeric, NUMERIC), ("miss", MissingIndicator(features="missing-only", error_on_new=False), NUMERIC),
             ("cat", categorical, CATEGORICAL)]
    encode = ColumnTransformer([p for p in parts if p[2]])
    return make_pipeline(encode, LogisticRegression(C=0.1, max_iter=3000))
'''

MONOTONE_HGB = HEADER + '''from sklearn.compose import ColumnTransformer
from sklearn.ensemble import HistGradientBoostingClassifier
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OrdinalEncoder
''' + COLUMNS + '''# +1 : risk increases with value; -1 decreases (features.yaml expected_direction); 0 unconstrained
MONOTONIC = {mono!r}


def build():
    parts = [("cat", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1, encoded_missing_value=-1,
                                    max_categories=250), CATEGORICAL),
             ("num", "passthrough", NUMERIC)]
    encode = ColumnTransformer([p for p in parts if p[2]])
    model = HistGradientBoostingClassifier(
        categorical_features=list(range(len(CATEGORICAL))) or None,
        monotonic_cst=[0] * len(CATEGORICAL) + [MONOTONIC.get(c, 0) for c in NUMERIC],
        learning_rate=0.05, max_iter=300, max_leaf_nodes=15, min_samples_leaf=200,
        l2_regularization=1.0, early_stopping=False, random_state=0,
    )
    return make_pipeline(encode, model)
'''

EBM = HEADER + '''from interpret.glassbox import ExplainableBoostingClassifier
from sklearn.compose import ColumnTransformer
from sklearn.pipeline import make_pipeline
from sklearn.preprocessing import OrdinalEncoder
''' + COLUMNS + '''

def build():
    # categories coded as numbers first: interpret 0.6.9 refuses pandas' string dtype; they stay nominal for the EBM
    parts = [("cat", OrdinalEncoder(handle_unknown="use_encoded_value", unknown_value=-1, encoded_missing_value=-2),
              CATEGORICAL),
             ("num", "passthrough", NUMERIC)]
    encode = ColumnTransformer([p for p in parts if p[2]])
    model = ExplainableBoostingClassifier(
        feature_names=CATEGORICAL + NUMERIC,
        feature_types=["nominal"] * len(CATEGORICAL) + ["continuous"] * len(NUMERIC),
        interactions=10, outer_bags=8, max_bins=256, max_interaction_bins=32,
        learning_rate=0.02, max_rounds=5000, early_stopping_rounds=100,
        min_samples_leaf=20, n_jobs=-1, random_state=0,
    )
    return make_pipeline(encode, model)
'''

AUTOGLUON = HEADER + '''from mlkit.automl import AutoGluonClassifier
''' + COLUMNS + '''# Settings fixed by frame (spec.baselines_autogluon); wrapper version and code
# are frozen here so changes update the file hash and invalidate the baseline.
TIME_LIMIT = {time_limit!r}          # seconds per fit (once per window)
PRESETS = {presets!r}
AUTOGLUON_VERSION = {ag_version!r}
WRAPPER_SHA256 = {wrapper_sha!r}   # mlkit/automl.py


def build():
    # fit only on this training window; AutoGluon internal validation is drawn from it
    return AutoGluonClassifier(time_limit=TIME_LIMIT, presets=PRESETS, eval_metric="roc_auc", seed=0)
'''

DOCS = {
    "splines_logit": "Regularized logistic regression (C=0.1) over cubic splines with 5 numeric quantile knots,\n"
                     "missingness indicators, categorical one-hot encoding (levels below 1% pooled).",
    "monotone_hgb": "HistGradientBoosting with native categories and expected_direction monotonic constraints,\n"
                    "fixed conservative settings (no grid: 1 comparison).",
    "ebm": "Explainable Boosting Machine (interpret-core), 10 automatically detected interactions.",
    "autogluon": "AutoGluon (autogluon.tabular): weighted ensemble of boosting, forests, linear models, and kNN,\n"
                 "time limit and presets fixed by the frame; no tuning on test windows.",
}
TEMPLATES = {"splines_logit": SPLINES_LOGIT, "monotone_hgb": MONOTONE_HGB, "ebm": EBM, "autogluon": AUTOGLUON}
FAMILIES = {"splines_logit": "LogisticRegression", "monotone_hgb": "HistGradientBoostingClassifier",
            "ebm": "ExplainableBoostingClassifier", "autogluon": "AutoGluon"}


def declared(spec: dict) -> tuple[list[str], list[str]]:
    """(baselines listed in the frame, unknown ones)."""
    names = spec.get("baselines") or []
    if isinstance(names, str):
        names = [names]
    return [str(n) for n in names], [str(n) for n in names if n not in KNOWN]


def leak_suspect_columns(spec: dict, registry: dict, cols: list[str]) -> list[str]:
    """Columns D6 would refuse (predict the target alone too well, no leak_ack): left out of every
    baseline, so a suspect column cannot get every baseline refused (eval XP, 2026-10-12)."""
    from . import dataquality, reference
    df = core.load_dev(spec)
    strength, _ = dataquality.used_strength(df, cols, spec)
    sus, _ = dataquality.leak_suspects(strength, registry, exempt=reference.columns(spec))
    return [s.split(" (AUC")[0] for s in sus]


def columns(registry: dict, dev: pd.DataFrame, drop=()) -> tuple[list[str], list[str], dict]:
    """(numeric, categorical, monotonic constraints) from the registry, restricted to dev columns."""
    num, cat, mono = [], [], {}
    for col, entry in registry.items():
        if entry.get("available") != "origination" or entry.get("excluded_by") or col in drop:
            continue
        if col not in dev.columns or dev[col].isna().all():
            continue
        kind = (entry.get("contract") or {}).get("type")
        is_num = kind == "numeric" or (kind is None and pd.api.types.is_numeric_dtype(dev[col])
                                       and not pd.api.types.is_bool_dtype(dev[col]))
        (num if is_num else cat).append(col)
        if is_num and entry.get("expected_direction") in ("+", "-"):
            mono[col] = 1 if entry["expected_direction"] == "+" else -1
    return num, cat, mono


def interpret_problem() -> str | None:
    """None if interpret can fit an EBM here; otherwise why not. Importing is not enough: interpret-core
    0.6.9 imports with numpy 2.5 but fails at the first fit (numpy.bool passed to its native library)."""
    try:
        import numpy as np
        from interpret.glassbox import ExplainableBoostingClassifier
    except ImportError:
        return "interpret is not installed (pip install interpret-core)"
    try:
        x = np.random.default_rng(0).random((200, 2))
        ExplainableBoostingClassifier(interactions=0, outer_bags=1, max_rounds=20, n_jobs=1).fit(x, (x[:, 0] > 0.5).astype(int))
    except Exception as exc:          # broken native layer, incompatible numpy, ...
        import interpret
        return (f"interpret {getattr(interpret, '__version__', '?')} is installed but unusable here "
                f"({type(exc).__name__}: {exc}); try a newer interpret-core version")
    return None


def autogluon_settings(spec: dict | None) -> dict:
    s = {**AUTOGLUON_DEFAULTS, **((spec or {}).get("baselines_autogluon") or {})}
    return {"time_limit": int(s["time_limit"]), "presets": str(s["presets"])}


def render(name: str, num: list[str], cat: list[str], mono: dict, spec: dict | None = None) -> str:
    extra = {}
    if name == "autogluon":
        from . import automl
        extra = {**autogluon_settings(spec), "ag_version": automl.autogluon_version(),
                 "wrapper_sha": config.sha256_file(Path(automl.__file__))}
    return TEMPLATES[name].format(name=name, doc=DOCS[name], n_num=len(num), n_cat=len(cat),
                                  num=num, cat=cat, mono=mono, family=FAMILIES[name], **extra)


def generate(names: list[str], registry: dict, dev: pd.DataFrame, drop=(), spec: dict | None = None) -> dict[str, str]:
    """Write model/baselines/<name>.py for each name; return {name: relative path}. Unchanged files are not rewritten."""
    num, cat, mono = columns(registry, dev, drop)
    out_dir = config.ROOT / BASELINE_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    paths = {}
    for name in names:
        if name == "ebm" and (why := interpret_problem()):
            print(f"baseline ebm SKIPPED : {why}. Other baselines continue.", file=sys.stderr)
            continue
        if name == "autogluon":
            from . import automl
            if why := automl.autogluon_problem():
                print(f"baseline autogluon SKIPPED : {why}. Other baselines continue.", file=sys.stderr)
                continue
        rel = f"{BASELINE_DIR}/{name}.py"
        text = render(name, num, cat, mono, spec)
        target = config.ROOT / rel
        if not target.exists() or target.read_text(encoding="utf-8") != text:
            target.write_text(text, encoding="utf-8")
        paths[name] = rel
    return paths


def already_run(runs: list[dict], path: str, fhash: str, chash: str):
    """An exploratory run of the same file, same frame, same code: counted once, never again."""
    done = [r for r in runs if r.get("status") == "exploratory" and r.get("pipeline") == path
            and r.get("frame_hash") == fhash and r.get("code_hash") == chash]
    return done[-1] if done else None


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(prog="python -m mlkit.baselines")
    ap.add_argument("--dry-run", action="store_true", help="generate the files, run nothing")
    args = ap.parse_args(argv)

    role = os.environ.get("OSML_ROLE", "explorer")
    if role not in ALLOWED_ROLES:
        print(f"mlkit.baselines is explorer/human-only (current role: {role}).", file=sys.stderr)
        return 10

    spec, registry = config.load_frame()["spec"], config.load_features()
    names, unknown = declared(spec)
    if unknown:
        print(f"UNKNOWN BASELINE in frame.yaml (spec.baselines): {', '.join(unknown)}. "
              f"Known: {', '.join(KNOWN)}. Only a frame: commit changes the list.", file=sys.stderr)
        return 9
    if not names:
        print("No baseline declared (spec.baselines absent from frame): nothing to do.")
        return 0

    dev = pd.read_csv(config.DEV_DIR / "features.csv.gz", low_memory=False)
    num, cat, _ = columns(registry, dev)
    drop = leak_suspect_columns(spec, registry, num + cat)
    if drop:
        print("features excluded from baselines (D6, suspected leakage, no leak_ack): " + ", ".join(drop))
    paths = generate(names, registry, dev, drop, spec)
    print("generated baselines: " + ", ".join(paths.values()))
    if args.dry_run:
        return 0

    from . import run
    fhash = config.frame_hash()
    if run.latest_reference(config.read_jsonl(config.REGISTRY_FILE), fhash) is None:
        print("No reference under this frame: starting `mlkit.run --reference`.")
        code = run.main(["--reference"])
        if code != 0:
            return code

    code = 0
    for name, path in paths.items():
        runs = config.read_jsonl(config.REGISTRY_FILE)
        prev = already_run(runs, path, fhash, core.code_hash(path))
        if prev is not None:
            print(f"{name}: already in registry ({prev['run_id']}, same frame and code) — not rerun.")
            continue
        code = run.main(["--pipeline", path, "--note", f"baseline automatic {name}"])
        if code == 4:          # this baseline refused (I5/D6): the others may still run
            continue
        if code != 0:          # stop, open stop, budget, gate, data: the sequence ends here
            break

    summary(paths, fhash, spec)
    return code


def summary(paths: dict, fhash: str, spec: dict) -> None:
    p = spec["metric_primary"]
    runs = config.read_jsonl(config.REGISTRY_FILE)
    rows = []
    for name, path in paths.items():
        r = already_run(runs, path, fhash, core.code_hash(path))
        if r is not None:
            rows.append((name, r))
    if not rows:
        return
    print(f"\nBaselines (frame {fhash}) :")
    for name, r in rows:
        g = r.get("gain", {})
        print(f"  {name:<14} {r['run_id']:<8} {p} {r['summary'][p]['mean']:.4f} · gain {g.get('mean', 0):+.4f} "
              f"± {g.get('std', 0):.4f} · {'conclusive' if r.get('conclusive') else 'non conclusive'}")
    print("These are references, not a starting point: under selection_rule mean_rank_all they enter "
          "the final average like any exploratory run. Explore the families and structures you choose.")


if __name__ == "__main__":
    sys.exit(main())
