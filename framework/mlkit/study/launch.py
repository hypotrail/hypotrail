"""Where the engine's Python lives and how to open the notebooks (v0.2a, WP-A1, remark R7).

A study's notebooks import ``mlkit``, which is installed in the engine's environment (the
``framework/.venv`` the CLI runs from), not in whatever interpreter an editor picks. So:

* ``hypotrail init`` writes ``<study>/.vscode/settings.json`` with
  ``python.defaultInterpreterPath`` set to the engine's Python, **only if that file is
  absent**; otherwise it returns a notice with the line to add (:func:`install_settings`);
* ``hypotrail init`` adds ``__marimo__/`` (Marimo's cache folder) to the study's
  ``.gitignore``, creating the file or appending the line once (:func:`install_gitignore`);
* :func:`deliverables` gives the exact commands that open the generated notebook read-only
  (``marimo run``) and the workbench for editing (``marimo edit``) with the engine's
  environment, for the init payload and ``status --summary``. Surfaces show or launch them;
  the engine never starts a process.

Nothing that exists is overwritten. Free of pandas, numpy, and scikit-learn.
"""
from __future__ import annotations

import json
import os
import shlex
import sys
from pathlib import Path

SETTINGS = '.vscode/settings.json'
INTERPRETER_KEY = 'python.defaultInterpreterPath'
GITIGNORE = '.gitignore'
MARIMO_CACHE = '__marimo__/'
AGENT_FILE = '.hypotrail/agent.json'
# The two notebooks and how each one is opened (R4, R7): the generated notebook is
# regenerated by the engine, so it opens read-only; the workbench is the junior's.
NOTEBOOKS = (('notebook', 'notebooks/study_generated.py', 'run'),
             ('workbench', 'notebooks/workbench.py', 'edit'))
LAUNCH_KEYS = ('mode', 'path', 'argv', 'shell')
DELIVERABLES_KEYS = ('interpreter', 'launch')
NOTICE_KEYS = ('code', 'audience', 'message', 'junior_message', 'line')


def framework_dir() -> Path:
    """The engine's uv project (``framework/``)."""
    return Path(__file__).resolve().parents[2]


def interpreter() -> str:
    """The engine's Python: ``framework/.venv/bin/python`` when it exists (the
    environment ``uv run --project framework`` uses), else the running interpreter.
    The venv path is kept as is (not resolved), as an editor expects it."""
    venv = framework_dir() / '.venv' / 'bin' / 'python'
    if venv.exists():
        return str(venv)
    return sys.executable


def install_settings(study_dir) -> dict | None:
    """Write ``.vscode/settings.json`` when absent; else a notice with the line to add.

    Returns None when the file was written or already names the engine's Python, else a
    notice ``{code, audience, message, junior_message, line}``."""
    study = Path(study_dir)
    path = study / SETTINGS
    python = interpreter()
    line = f'"{INTERPRETER_KEY}": {json.dumps(python)}'
    if not path.exists() and not path.is_symlink():
        path.parent.mkdir(parents=True, exist_ok=True)
        text = json.dumps({INTERPRETER_KEY: python}, indent=2) + '\n'
        fd = os.open(path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
        with os.fdopen(fd, 'w', encoding='utf-8') as handle:
            handle.write(text)
        return None
    try:
        existing = path.read_text(encoding='utf-8')
    except (OSError, UnicodeDecodeError):
        existing = ''
    if json.dumps(python) in existing and INTERPRETER_KEY in existing:
        return None
    return {'code': 'vscode_settings_kept', 'audience': 'agent',
            'message': f'{SETTINGS} already exists and was not changed. To run the notebooks '
                       f'with the engine\'s Python (it has mlkit and Marimo), add this line to '
                       f'it: {line}',
            'junior_message': 'Your editor settings for this folder already existed, so they '
                              'were left as they are. To open the notebooks with the right '
                              'Python, the assistant can show you the one line to add.',
            'line': line}


def install_gitignore(study_dir) -> bool:
    """Add ``__marimo__/`` to the study's ``.gitignore`` once; True when written."""
    path = Path(study_dir) / GITIGNORE
    existing = ''
    if path.exists():
        try:
            existing = path.read_text(encoding='utf-8')
        except (OSError, UnicodeDecodeError):
            return False
    lines = {x.strip() for x in existing.splitlines()}
    if MARIMO_CACHE in lines or MARIMO_CACHE.rstrip('/') in lines:
        return False
    sep = '' if not existing or existing.endswith('\n') else '\n'
    with open(path, 'a', encoding='utf-8') as handle:
        handle.write(f'{sep}{MARIMO_CACHE}\n')
    return True


def _recorded_cli(study: Path) -> list[str] | None:
    try:
        record = json.loads((study / AGENT_FILE).read_text(encoding='utf-8'))
        argv = record['cli']['argv']
    except (OSError, ValueError, KeyError, TypeError):
        return None
    return [str(a) for a in argv] if isinstance(argv, list) else None


def _marimo_prefix(study: Path) -> list[str]:
    """The command prefix that runs Marimo in the engine's environment: the uv project
    the study's agent runs the CLI with (``.hypotrail/agent.json``), else this engine's
    project when uv runs it, else the engine's Python."""
    argv = _recorded_cli(study)
    if argv and argv[:3] == ['uv', 'run', '--project'] and len(argv) > 3:
        return ['uv', 'run', '--project', argv[3], 'marimo']
    from . import agent_files

    cli = agent_files.cli_command()
    if cli['how'] == 'uv_project':
        return ['uv', 'run', '--project', str(framework_dir()), 'marimo']
    return [interpreter(), '-m', 'marimo']


def deliverables(study_dir) -> dict:
    """``{interpreter, launch: {notebook, workbench}}``; each launch is ``{mode, path,
    argv, shell}`` with absolute paths (an argument list, to run without a shell)."""
    study = Path(study_dir).resolve()
    prefix = _marimo_prefix(study)
    launch = {}
    for name, rel, mode in NOTEBOOKS:
        path = str(study / rel)
        argv = [*prefix, mode, path]
        launch[name] = {'mode': mode, 'path': rel, 'argv': argv, 'shell': shlex.join(argv)}
    return {'interpreter': interpreter(), 'launch': launch}
