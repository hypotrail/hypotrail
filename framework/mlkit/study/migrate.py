"""Explicit migration from a companion ``project.json`` to a ``hypotrail.case/1`` case.

``project.json`` (schema ``hypotrail.project/1``) is a companion tutorial contract.
Its statuses describe tutorial choices, not human decisions, so the migration never
carries a confirmation over. The mapping (plan WP0.4) is:

==================  ===================================  =======================
Companion status    Companion source                     Case status
==================  ===================================  =======================
``confirmed``       tutorial or scenario                 ``scenario_assumption``
``confirmed``       dataset documentation                ``documented_fact``
``confirmed``       anything else                        ``scenario_assumption``
``proposed``        any                                  ``scenario_assumption``
``unknown``         any                                  ``unknown``
==================  ===================================  =======================

Availability at prediction time from ``project.json`` becomes ``scenario_assumption``
(``yes``/``no``) or ``unknown``: the dataset documentation describes variables, it
does not establish when a value becomes known. Every data column receives an entry;
a column that ``project.json`` does not describe gets an ``unknown`` availability.

What ``project.json`` does not carry (how to read the file, the positive label,
line-cited documentation, structural observations) comes from an optional
``case-supplement.yaml`` (``hypotrail.case-supplement/1``) next to it. A supplement
may set availability to ``documented_fact`` only for ``not_available`` and only with
a source that cites an existing file of the use case by line (``path:line``).

Usage::

    uv run --project framework python -m mlkit.study.migrate use-cases/<id> --write
    uv run --project framework python -m mlkit.study.migrate use-cases/<id> --check
"""
from __future__ import annotations

import argparse
import copy
import csv
import hashlib
import json
import re
import sys
from pathlib import Path
from typing import Any

import yaml

from . import case as case_contract

TOOL = 'mlkit.study.migrate'
TOOL_VERSION = 1
SOURCE_SCHEMA = 'hypotrail.project/1'
SUPPLEMENT_SCHEMA = 'hypotrail.case-supplement/1'
SUPPLEMENT_FILE = 'case-supplement.yaml'
PROJECT_FILE = 'project.json'
RESULTS_FILE = 'results.json'

TASKS = {'binary_classification': 'binary', 'regression': 'regression'}
TYPES = {'numeric': 'numeric', 'integer': 'integer', 'binary': 'binary', 'category': 'category',
         'ordinal': 'ordinal', 'text': 'string', 'string': 'string', 'date': 'date'}
ROLES = {'feature': 'feature', 'target': 'target', 'identifier': 'identifier', 'time': 'time',
         'excluded': 'feature', 'group': 'feature'}
ROLE_NOTES = {
    'excluded': 'companion role "excluded" is a tutorial modelling choice; exclusion is a study '
                'decision, so the case role is "feature"',
    'group': 'companion role "group" marks a reporting breakdown, not a repeated-entity '
             'group; the case role is "feature" and no group column is declared from it',
}
SUPPLEMENT_KEYS = ('schema', 'purpose', 'dataset', 'target', 'facts', 'variables', 'structure',
                   'prior_exposure', 'notes')
SUPPLEMENT_DATASET_KEYS = ('sep', 'header', 'quotechar', 'na_values', 'encoding', 'decimal',
                           'column_names')
CITATION = re.compile(r'([\w][\w./-]*):(\d+)')
TEMPLATE = re.compile(r'\{\{.*?\}\}')

HEADER_COMMENT = (
    '# Generated by {tool} (version {version}) from {source}{supplement}.\n'
    '# Do not edit by hand: change {edit} and regenerate with\n'
    '#   uv run --project framework python -m {tool} <use-case dir> --write\n'
    '# A case states facts and assumptions; human decisions live in study state.\n')


class MigrationError(ValueError):
    """The companion project cannot be migrated without guessing."""


def _sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


class _Log:
    def __init__(self):
        self.rules: list[str] = []

    def __call__(self, path: str, change: str) -> None:
        self.rules.append(f'{path}: {change}')


def _documentation_names(folder: Path, dataset: Path) -> list[str]:
    """Names of the files shipped with the dataset, which a source may cite."""
    return sorted(p.name for p in dataset.parent.iterdir()
                  if p.is_file() and p.resolve() != dataset.resolve())


def _is_documentation(source: str, doc_names: list[str]) -> bool:
    low = source.lower()
    return 'documentation' in low or any(name.lower() in low for name in doc_names)


def _status(status: str, source: str, doc_names: list[str], path: str, log: _Log) -> str:
    low = (source or '').lower()
    if status == 'confirmed':
        if 'tutorial' in low or 'scenario' in low:
            log(path, 'companion tutorial assertion -> scenario_assumption')
            return 'scenario_assumption'
        if _is_documentation(source or '', doc_names):
            log(path, 'companion documentation assertion -> documented_fact')
            return 'documented_fact'
        log(path, 'companion assertion with no documentation source -> scenario_assumption')
        return 'scenario_assumption'
    if status == 'proposed':
        log(path, 'companion proposal -> scenario_assumption')
        return 'scenario_assumption'
    if status == 'unknown':
        return 'unknown'
    raise MigrationError(f'{path}: unknown companion status {status!r}')


def _availability(value: str, path: str, log: _Log) -> dict:
    if value == 'yes':
        log(path, 'companion "yes" -> available_at_prediction, scenario_assumption')
        return {'value': 'available_at_prediction', 'status': 'scenario_assumption',
                'source': 'Companion tutorial (project.json); the dataset documentation does '
                          'not establish availability at prediction time'}
    if value == 'no':
        log(path, 'companion "no" -> not_available, scenario_assumption')
        return {'value': 'not_available', 'status': 'scenario_assumption',
                'source': 'Companion tutorial (project.json); not established by the dataset '
                          'documentation'}
    if value == 'unknown':
        return {'value': 'unknown', 'status': 'unknown',
                'source': 'Companion tutorial (project.json): availability unknown'}
    raise MigrationError(f'{path}: unknown companion availability {value!r}')


def _load_supplement(folder: Path, supplement) -> tuple[dict, Path | None]:
    path = Path(supplement) if supplement is not None else folder / SUPPLEMENT_FILE
    if not path.is_file():
        if supplement is not None:
            raise MigrationError(f'Supplement not found: {path}')
        return {}, None
    doc = yaml.safe_load(path.read_text(encoding='utf-8')) or {}
    if not isinstance(doc, dict) or doc.get('schema') != SUPPLEMENT_SCHEMA:
        raise MigrationError(f'{path.name}: schema must be "{SUPPLEMENT_SCHEMA}"')
    unknown = set(doc) - set(SUPPLEMENT_KEYS)
    if unknown:
        raise MigrationError(f'{path.name}: unknown keys {sorted(unknown)}')
    unknown = set(doc.get('dataset', {})) - set(SUPPLEMENT_DATASET_KEYS)
    if unknown:
        raise MigrationError(f'{path.name}: unknown dataset keys {sorted(unknown)}')
    claims = case_contract.confirmation_claims(doc)
    if claims:
        raise MigrationError(f'{path.name}: a supplement never records a confirmation: {claims}')
    return doc, path


def _cites_existing_file(source: str, folder: Path) -> bool:
    for match in CITATION.finditer(source or ''):
        candidate = (folder / match.group(1)).resolve()
        if candidate.is_relative_to(folder.resolve()) and candidate.is_file():
            lines = candidate.read_bytes().count(b'\n') + 1
            if 1 <= int(match.group(2)) <= lines:
                return True
    return False


def _check_supplement_statement(node: Any, path: str, folder: Path) -> None:
    """Supplement documented facts must cite a shipped file by line."""
    if isinstance(node, dict):
        if node.get('status') == 'documented_fact' and not _cites_existing_file(
                node.get('source', ''), folder):
            raise MigrationError(f'{path}: a documented_fact in the supplement must cite an '
                                 f'existing use-case file as path:line')
        for key, value in node.items():
            _check_supplement_statement(value, f'{path}.{key}', folder)
    elif isinstance(node, list):
        for i, item in enumerate(node):
            _check_supplement_statement(item, f'{path}[{i}]', folder)


def _read_columns(dataset: Path, read: dict) -> list[str]:
    if not read.get('header', True):
        names = read.get('column_names')
        if not names:
            raise MigrationError('A headerless dataset needs dataset.column_names in the supplement')
        return list(names)
    with open(dataset, encoding=read.get('encoding', 'utf-8'), newline='') as handle:
        first = handle.readline().rstrip('\r\n')
    if read['sep'] == case_contract.WHITESPACE_SEP:
        return first.split()
    return next(csv.reader([first], delimiter=read['sep'], quotechar=read.get('quotechar', '"')))


def _inferred_type(dataset: Path, read: dict, column: str, columns: list[str]) -> str:
    import pandas as pd   # deferred: only a migration of an undescribed column needs it

    frame = pd.read_csv(dataset, sep=r'\s+' if read['sep'] == case_contract.WHITESPACE_SEP
                        else read['sep'], header=0 if read.get('header', True) else None,
                        names=None if read.get('header', True) else columns,
                        quotechar=read.get('quotechar', '"'), na_values=read.get('na_values'),
                        keep_default_na=False, usecols=[column])
    kind = frame[column].dtype.kind
    return {'i': 'integer', 'u': 'integer', 'f': 'numeric', 'b': 'binary'}.get(kind, 'category')


def _merge(base: dict, override: dict) -> dict:
    out = copy.deepcopy(base)
    for key, value in override.items():
        out[key] = copy.deepcopy(value)
    return out


def from_companion_project(path, *, supplement=None) -> dict:
    """Build a ``hypotrail.case/1`` document from a companion ``project.json``.

    ``path`` is the ``project.json`` file or its use-case directory. Nothing is
    written; ``project.json`` and ``results.json`` are only read. Raises
    :class:`MigrationError` instead of guessing, and the returned document passes
    :func:`mlkit.study.case.check_document`.
    """
    path = Path(path)
    project_path = path / PROJECT_FILE if path.is_dir() else path
    folder = project_path.parent
    project = json.loads(project_path.read_text(encoding='utf-8'))
    if project.get('schema') != SOURCE_SCHEMA:
        raise MigrationError(f'{project_path.name}: schema must be "{SOURCE_SCHEMA}"')
    sup, sup_path = _load_supplement(folder, supplement)
    _check_supplement_statement({k: v for k, v in sup.items() if k != 'dataset'}, 'supplement',
                                folder)
    log = _Log()
    notes = ['project.json and results.json are companion tutorial contracts. Nothing in them is '
             'a human decision, and this case imports none of their choices as one.']

    # Dataset.
    ds = project['dataset']
    dataset_path = (folder / ds['path']).resolve()
    if not dataset_path.is_relative_to(folder.resolve()) or not dataset_path.is_file():
        raise MigrationError(f'Dataset not found inside the use case: {ds["path"]}')
    actual = _sha(dataset_path)
    if actual != ds['sha256']:
        raise MigrationError(f'Dataset sha256 {actual} differs from project.json {ds["sha256"]}')
    read = {'sep': ',', 'header': True, 'quotechar': '"', 'encoding': 'utf-8', 'decimal': '.',
            **sup.get('dataset', {})}
    columns = _read_columns(dataset_path, read)
    data = dataset_path.read_bytes()
    lines = data.count(b'\n') + (0 if not data or data.endswith(b'\n') else 1)
    rows = lines - (1 if read['header'] else 0)
    if rows != ds['rows']:
        raise MigrationError(f'project.json declares {ds["rows"]} rows; the file has {rows} '
                             f'data lines')
    doc_names = _documentation_names(folder, dataset_path)

    # Variables, in data column order.
    described = {v['name']: v for v in project['variables']}
    stray = sorted(set(described) - set(columns))
    if stray:
        raise MigrationError(f'project.json describes columns absent from the data: {stray}')
    overrides = sup.get('variables', {})
    stray = sorted(set(overrides) - set(columns))
    if stray:
        raise MigrationError(f'The supplement describes columns absent from the data: {stray}')
    variables = []
    for name in columns:
        p = f'variables.{name}'
        if name in described:
            v = described[name]
            if v['type'] not in TYPES or v['role'] not in ROLES:
                raise MigrationError(f'{p}: unsupported companion type or role '
                                     f'{v["type"]!r}/{v["role"]!r}')
            if v['role'] in ROLE_NOTES:
                log(f'{p}.role', ROLE_NOTES[v['role']])
            status = _status(v['status'], v['source'], doc_names, f'{p}.status', log)
            entry = {'name': name, 'type': TYPES[v['type']], 'role': ROLES[v['role']]}
            if v.get('unit') is not None:
                entry['unit'] = v['unit']
            entry.update({
                'description': v['description'], 'status': status, 'source': v['source'],
                'availability': _availability(v['available_at_prediction'],
                                              f'{p}.availability', log),
                'special_values': [{'value': sv['value'], 'meaning': sv['meaning'],
                                    'status': status, 'source': v['source']}
                                   for sv in v.get('special_values', [])]})
        else:
            log(p, 'not described in project.json: status and availability unknown')
            entry = {'name': name, 'type': _inferred_type(dataset_path, read, name, columns),
                     'role': 'feature', 'description': 'Not described in project.json.',
                     'status': 'unknown', 'source': 'Not described in project.json',
                     'availability': {'value': 'unknown', 'status': 'unknown',
                                      'source': 'Not described in project.json; availability at '
                                                'prediction time is not documented'},
                     'special_values': []}
        if name in overrides:
            changed = sorted(overrides[name])
            log(p, f'supplement sets {", ".join(changed)}')
            entry = _merge(entry, overrides[name])
        order = ('name', 'type', 'role', 'unit', 'format', 'description', 'status', 'source',
                 'availability', 'special_values')
        entry = {k: entry[k] for k in order if k in entry} | {
            k: v for k, v in entry.items() if k not in order}
        a = entry['availability']
        if a.get('status') == 'documented_fact' and a.get('value') != 'not_available':
            raise MigrationError(f'{p}.availability: documented_fact is allowed only for '
                                 f'not_available')
        variables.append(entry)
    by_name = {v['name']: v for v in variables}

    # Task and target.
    if project['problem_type'] not in TASKS:
        raise MigrationError(f'Unsupported companion problem_type {project["problem_type"]!r}')
    task = TASKS[project['problem_type']]
    targets = [v['name'] for v in variables if v['role'] == 'target']
    if len(targets) != 1:
        raise MigrationError(f'Expected exactly one target variable, found {targets}')
    target = {'column': targets[0], 'positive_label': None}
    target.update(sup.get('target', {}))
    if task == 'binary' and target['positive_label'] in (None, ''):
        raise MigrationError('A binary case needs target.positive_label in the supplement; '
                             'the migration does not guess it')

    # Facts.
    fact_overrides = sup.get('facts', {})
    stray = sorted(set(fact_overrides) - {f['id'] for f in project['facts']})
    if stray:
        raise MigrationError(f'The supplement overrides unknown facts: {stray}')
    facts = []
    for f in project['facts']:
        p = f'facts.{f["id"]}'
        entry = {'id': f['id'], 'value': f['value'],
                 'status': _status(f['status'], f['source'], doc_names, f'{p}.status', log),
                 'source': f['source']}
        if f['id'] in fact_overrides:
            log(p, f'supplement sets {", ".join(sorted(fact_overrides[f["id"]]))}')
            entry = _merge(entry, fact_overrides[f['id']])
        facts.append(entry)

    # Structure.
    fact_by_id = {f['id']: f for f in facts}
    unit = fact_by_id.get('observation_unit')
    times = [v['name'] for v in variables if v['role'] == 'time']
    groups = [v['name'] for v in variables if v['role'] == 'group_id']
    if len(times) > 1 or len(groups) > 1:
        raise MigrationError('At most one time column and one group column are supported')
    structure = {
        'row_unit': ({'value': unit['value'], 'status': unit['status'], 'source': unit['source']}
                     if unit else {'value': None, 'status': 'unknown', 'source': 'Not documented'}),
        'group_column': ({'value': groups[0], 'status': by_name[groups[0]]['status'],
                          'source': by_name[groups[0]]['source']} if groups else
                         {'value': None, 'status': 'unknown',
                          'source': 'No group column declared in project.json'}),
        'time_column': ({'value': times[0], 'status': by_name[times[0]]['status'],
                         'source': by_name[times[0]]['source']} if times else
                        {'value': None, 'status': 'unknown',
                         'source': 'No time column declared in project.json'}),
        'duplicates': {'value': None, 'status': 'unknown', 'source': 'Not documented'},
    }
    for key, value in sup.get('structure', {}).items():
        if key not in structure:
            raise MigrationError(f'Unknown structure key in the supplement: {key}')
        log(f'structure.{key}', 'set by the supplement')
        structure[key] = copy.deepcopy(value)

    # Prior exposure: tutorial outputs already published for this dataset.
    prior = []
    results_path = folder / RESULTS_FILE
    if results_path.is_file():
        results = json.loads(results_path.read_text(encoding='utf-8'))
        for protocol in results.get('protocols', []):
            prior.append({
                'value': f'Tutorial outputs for protocol "{protocol["id"]}" ({protocol["label"]}. '
                         f'{protocol["description"]}) are published in results.json. The rows '
                         f'used there are not unseen, and its validation is not independent '
                         f'evidence.',
                'status': 'observed',
                'source': f'results.json (sha256 {_sha(results_path)})'})
    prior += copy.deepcopy(sup.get('prior_exposure', []))

    for item in ds.get('transformations', []):
        notes.append(f'Companion dataset note: {item}')
    for item in project.get('limitations', []):
        notes.append(f'Companion limitation: {item}')
    for item in project.get('ai_guidance', []):
        notes.append(f'Companion guidance: {item}')
    notes += list(sup.get('notes', []))

    provenance = dict(ds.get('provenance', {}))
    kind = 'public_dataset' if provenance.get('doi') or provenance.get('source_url') else 'unspecified'
    dataset = {'path': ds['path'], 'format': 'csv', 'sep': read['sep'],
               'encoding': read['encoding'], 'decimal': read['decimal'],
               'header': read['header'], 'sha256': ds['sha256'], 'rows': rows,
               'columns': len(columns)}
    if 'quotechar' in sup.get('dataset', {}):
        dataset['quotechar'] = read['quotechar']
    if 'na_values' in read:
        dataset['na_values'] = list(read['na_values'])
    first = 'L2' if read['header'] else 'L1'
    migration = {'from': PROJECT_FILE, 'from_schema': SOURCE_SCHEMA,
                 'from_sha256': _sha(project_path)}
    if sup_path is not None:
        migration.update({'supplement': sup_path.name, 'supplement_sha256': _sha(sup_path)})
    migration.update({'tool': TOOL, 'tool_version': TOOL_VERSION, 'rules': log.rules,
                      'notes': notes})
    document = {
        'schema': case_contract.SCHEMA,
        'id': project['id'],
        'title': project['title'],
        'description': project['description'],
        'provenance': {'kind': kind, **provenance},
        'dataset': dataset,
        'target': target,
        'row_key': {'rule': case_contract.ROW_KEY_RULE, 'format': case_contract.ROW_KEY_FORMAT,
                    'description': f'Physical 1-based line number in {Path(ds["path"]).name}'
                                   f'{"; the header is line 1" if read["header"] else "; the file has no header"}'
                                   f', so the first data row is {first}. The key is anchored to '
                                   f'the dataset sha256.'},
        'facts': facts,
        'variables': variables,
        'special_values': [{'column': v['name'], **sv} for v in variables
                           for sv in v['special_values']],
        'structure': structure,
        'task': task,
        'prior_exposure': prior,
        'migration': migration,
    }
    leftovers = [p for p, node in case_contract._walk(document, '')
                 if isinstance(node, str) and TEMPLATE.search(node)]
    if leftovers:
        raise MigrationError(f'Companion template placeholders must be replaced by the '
                             f'supplement: {leftovers}')
    case_contract.check_document(document)
    return document


def render(document: dict) -> str:
    """Deterministic YAML text for ``document``, with a provenance header comment."""
    m = document.get('migration', {})
    header = HEADER_COMMENT.format(
        tool=TOOL, version=TOOL_VERSION, source=m.get('from', PROJECT_FILE),
        supplement=f' and {m["supplement"]}' if m.get('supplement') else '',
        edit=m.get('supplement', SUPPLEMENT_FILE))
    return header + yaml.safe_dump(document, sort_keys=False, allow_unicode=True, width=100)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description='Migrate a companion project.json to case.yaml.')
    parser.add_argument('use_case', type=Path, help='use-case directory containing project.json')
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument('--write', action='store_true', help='write case.yaml')
    mode.add_argument('--check', action='store_true',
                      help='exit 1 if case.yaml differs from a fresh migration')
    args = parser.parse_args(argv)
    try:
        text = render(from_companion_project(args.use_case))
    except (MigrationError, case_contract.CaseError) as exc:
        print(f'migration refused: {exc}', file=sys.stderr)
        return 2
    out = args.use_case / case_contract.CASE_FILE
    if args.write:
        out.write_text(text, encoding='utf-8')
        print(out)
    elif args.check:
        current = out.read_text(encoding='utf-8') if out.is_file() else None
        if current != text:
            print(f'{out} differs from a fresh migration', file=sys.stderr)
            return 1
        print(f'{out} is up to date')
    else:
        sys.stdout.write(text)
    return 0


if __name__ == '__main__':
    sys.exit(main())
