"""Study agent instructions installed by ``hypotrail init`` (plan §5, WP4.1).

The templates live in ``mlkit/study/agent/`` under names that Claude Code and Copilot
do **not** load (``CLAUDE.md.in``, ``dot-claude/``), so a developer session in this
repository never picks up the study agent's rules. :data:`TARGETS` maps each template to
its real name in the study workspace, for Claude Code and, from the same source, for
GitHub Copilot (generated, **not tested**: directive A1).

=============================================  ==============================================
template (``mlkit/study/agent/``)              study workspace
=============================================  ==============================================
``CLAUDE.md.in``                               ``CLAUDE.md``, ``.github/copilot-instructions.md``
``dot-claude/skills/hypotrail-study/SKILL.md`` ``.claude/skills/hypotrail-study/SKILL.md``,
                                               ``.github/skills/hypotrail-study/SKILL.md``
``dot-claude/commands/hypotrail-resume.md``    ``.claude/commands/hypotrail-resume.md``,
                                               ``.github/prompts/hypotrail-resume.prompt.md``
=============================================  ==============================================

Placeholders are replaced at install: ``{{HYPOTRAIL}}`` by the exact command that runs
the CLI (:func:`cli_command`), ``{{STUDY}}`` by the absolute study directory,
``{{GLOSSARY}}`` by the absolute path of ``content/glossary.yaml``, and ``{{SKILL}}`` by
the skill path of the target agent. The command is also written to
``.hypotrail/agent.json`` (``hypotrail.agent/1``).

Nothing that exists is overwritten: an existing target is reported under
``skipped_existing``.
"""
from __future__ import annotations

import os
import re
import shlex
import shutil
import sys
from pathlib import Path
from typing import Mapping

SOURCE = Path(__file__).resolve().parent / 'agent'
README = 'README.md'
AGENT_FILE = 'agent.json'
SCHEMA = 'hypotrail.agent/1'
CLI_ENV = 'HYPOTRAIL_CLI'
GLOSSARY = Path(__file__).resolve().parent / 'content' / 'glossary.yaml'
COPILOT_HEADER = ('<!-- Generated by hypotrail init from the same source as the Claude Code '
                  'instructions ({source}). Not tested with GitHub Copilot (directive A1). -->')
CLAUDE, COPILOT = 'claude', 'copilot'
SKILL_PATHS = {CLAUDE: '.claude/skills/hypotrail-study/SKILL.md',
               COPILOT: '.github/skills/hypotrail-study/SKILL.md'}

# template -> ((target, flavour), ...)
TARGETS: dict[str, tuple[tuple[str, str], ...]] = {
    'CLAUDE.md.in': (('CLAUDE.md', CLAUDE), ('.github/copilot-instructions.md', COPILOT)),
    'dot-claude/skills/hypotrail-study/SKILL.md': (
        ('.claude/skills/hypotrail-study/SKILL.md', CLAUDE),
        ('.github/skills/hypotrail-study/SKILL.md', COPILOT)),
    'dot-claude/commands/hypotrail-resume.md': (
        ('.claude/commands/hypotrail-resume.md', CLAUDE),
        ('.github/prompts/hypotrail-resume.prompt.md', COPILOT)),
}
# Names an agent loads from a directory: no template may be stored under one of them.
LOADED_NAMES = ('CLAUDE.md', 'CLAUDE.local.md', 'AGENTS.md', '.claude', '.github')
_PLACEHOLDER = re.compile(r'\{\{([A-Z_]+)\}\}')


def default_target(rel: str) -> str:
    """Workspace path of a template not listed in :data:`TARGETS`:
    ``dot-<name>/`` becomes ``.<name>/`` and a trailing ``.in`` is dropped."""
    parts = [('.' + p[4:]) if p.startswith('dot-') else p for p in rel.split('/')]
    path = '/'.join(parts)
    return path[:-3] if path.endswith('.in') else path


def templates() -> list[str]:
    """Every template file (relative POSIX paths), the README excluded."""
    if not SOURCE.is_dir():
        return []
    return sorted(p.relative_to(SOURCE).as_posix() for p in SOURCE.rglob('*')
                  if p.is_file() and p.name != README and '__pycache__' not in p.parts)


def targets(rel: str) -> tuple[tuple[str, str], ...]:
    return TARGETS.get(rel, ((default_target(rel), CLAUDE),))


def cli_command() -> dict:
    """How an agent runs the CLI from the study workspace.

    ``HYPOTRAIL_CLI`` (a shell command) wins. Otherwise, when this engine is the
    ``framework/`` uv project and ``uv`` is on PATH, ``uv run --project <framework>
    hypotrail`` (the locked environment, from any directory). Otherwise the current
    interpreter with the engine on ``PYTHONPATH``.
    """
    framework = Path(__file__).resolve().parents[2]
    override = os.environ.get(CLI_ENV, '').strip()
    if override:
        argv, how = shlex.split(override), 'override'
    elif (framework / 'pyproject.toml').is_file() and shutil.which('uv'):
        argv, how = ['uv', 'run', '--project', str(framework), 'hypotrail'], 'uv_project'
    else:
        argv, how = ['env', f'PYTHONPATH={framework}', sys.executable, '-m',
                     'mlkit.study.cli'], 'python_module'
    return {'argv': argv, 'shell': shlex.join(argv), 'how': how}


def render(text: str, *, flavour: str, values: Mapping[str, str], source: str) -> str:
    """``text`` with its placeholders replaced; a Copilot copy gets a header comment
    (after the front matter, which must stay first)."""
    vals = dict(values, SKILL=SKILL_PATHS[flavour])
    unknown = sorted({m.group(1) for m in _PLACEHOLDER.finditer(text)} - set(vals))
    if unknown:
        raise ValueError(f'unknown placeholders in {source}: {", ".join(unknown)}')
    out = _PLACEHOLDER.sub(lambda m: vals[m.group(1)], text)
    if flavour == COPILOT:
        header = COPILOT_HEADER.format(source=f'mlkit/study/agent/{source}')
        if out.startswith('---\n'):
            end = out.index('\n---\n', 4) + len('\n---\n')
            front = out[:end]
            if source.endswith('commands/hypotrail-resume.md'):
                front = front.replace('---\n', '---\nmode: agent\n', 1)
            out = front + header + '\n' + out[end:]
        else:
            out = header + '\n\n' + out
    return out


def install(study_dir) -> dict:
    """Copy the instructions into ``study_dir`` and record ``.hypotrail/agent.json``.

    Returns the ``init.agent_instructions`` payload: ``{source, copied,
    skipped_existing, status, cli, agent_file}``.
    """
    from .store import atomic_write_json   # writer side: init only

    study = Path(study_dir).resolve()
    cli = cli_command()
    values = {'HYPOTRAIL': cli['shell'], 'STUDY': shlex.quote(str(study)),
              'GLOSSARY': str(GLOSSARY)}
    copied, skipped = [], []
    files = {}
    for rel in templates():
        text = (SOURCE / rel).read_text(encoding='utf-8')
        for target, flavour in targets(rel):
            dest = study / target
            if dest.exists():
                skipped.append(target)
                continue
            dest.parent.mkdir(parents=True, exist_ok=True)
            data = render(text, flavour=flavour, values=values, source=rel)
            fd = os.open(dest, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o644)
            with os.fdopen(fd, 'w', encoding='utf-8') as handle:
                handle.write(data)
            copied.append(target)
            files[target] = {'template': rel, 'flavour': flavour,
                             'tested': flavour == CLAUDE}
    agent_file = study / '.hypotrail' / AGENT_FILE
    record = {'schema': SCHEMA, 'study': str(study), 'cli': cli,
              'invocation': f'{cli["shell"]} <command> ... --study {shlex.quote(str(study))}',
              'glossary': str(GLOSSARY), 'files': files,
              'note': 'Run every hypotrail command with this invocation. The Copilot files are '
                      'generated from the same templates and are not tested (directive A1).'}
    if not agent_file.exists():
        atomic_write_json(agent_file, record)
    status = 'copied' if copied else ('kept_existing' if skipped else 'no_templates_yet')
    return {'source': str(SOURCE), 'copied': copied, 'skipped_existing': skipped,
            'status': status, 'cli': cli['shell'],
            'agent_file': f'.hypotrail/{AGENT_FILE}'}
