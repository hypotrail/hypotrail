"""Study agent instructions installed by ``hypotrail init`` (plan §5, WP4.1).

The templates live in ``mlkit/study/agent/`` under names that Claude Code and Copilot
do **not** load (``CLAUDE.md.in``, ``dot-claude/``), so a developer session in this
repository never picks up the study agent's rules. :data:`TARGETS` maps each template to
its real name in the study workspace, for Claude Code and, from the same source, for
GitHub Copilot (generated, **not tested**: directive A1).

=============================================  ==============================================
template (``mlkit/study/agent/``)              study workspace
=============================================  ==============================================
``CLAUDE.md.in``                               ``CLAUDE.md``, ``.github/copilot-instructions.md``
``dot-claude/skills/hypotrail-study/SKILL.md`` ``.claude/skills/hypotrail-study/SKILL.md``,
                                               ``.github/skills/hypotrail-study/SKILL.md``
``dot-claude/commands/hypotrail-resume.md``    ``.claude/commands/hypotrail-resume.md``,
                                               ``.github/prompts/hypotrail-resume.prompt.md``
``copilot-agent.md.in``                        ``.github/agents/hypotrail.agent.md`` (Copilot
                                               only: the custom agent that may use VS Code's
                                               ask-questions tool)
=============================================  ==============================================

Placeholders are replaced at install: ``{{HYPOTRAIL}}`` by the exact command that runs
the CLI (:func:`cli_command`), ``{{STUDY}}`` by the absolute study directory,
``{{GLOSSARY}}`` by the absolute path of the study's copy of ``content/glossary.yaml``
(:data:`STUDY_GLOSSARY`, copied at install so the agent never reads the engine's source
tree, D10), ``{{SKILL}}`` by the skill path of the target agent, and ``{{CHOICE_TOOL}}``
by the interactive choice tool of the target agent (Claude Code's ``AskUserQuestion``,
VS Code's ``#tool:vscode/askQuestions``), and ``{{RUN_NOTICE}}``, ``{{BLOCK_PLACE}}``,
``{{CHOICE_STEPS}}``, ``{{EXPLAIN_FIRST}}``, ``{{TEXT_FALLBACK}}``, ``{{PAUSE_CARRIER}}``
and ``{{PANEL_LINE_PLACE}}`` by where that agent's junior reads a pause
(:data:`FLAVOUR_TEXTS`: Copilot shows only the last message of a turn and the picker; the
last three are empty for Claude Code).
The command is also written to ``.hypotrail/agent.json`` (``hypotrail.agent/1``).

Nothing that exists is overwritten: an existing target is reported under
``skipped_existing``.

Task blocks (M3). A template line ``<!-- hypotrail:task binary -->`` or
``<!-- hypotrail:task regression -->`` opens a block that is installed only in a study of
that task; ``<!-- hypotrail:end -->`` closes it. Marker lines are never installed, so a
regression study's instructions hold no vocabulary of a decision rule on scores, and a
binary study's instructions are unchanged. A regression study's glossary copy holds the
regression glossary (:func:`mlkit.study.texts.glossary_terms`).
"""
